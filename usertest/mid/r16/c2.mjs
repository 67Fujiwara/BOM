// c2: 型式変更後の再見積と「頼むつもりの商社」。(a) サンプルの見積済の行（記録なし）を一部の商社に再見積、(b) メーカが変わった行
import { launch, check, log, summary } from './lib.mjs'
import { helpers } from './h.mjs'
const t = await launch(); const { page } = t; const h = helpers(t)
await t.open('design'); await t.press('1')
let p = await t.proj()
const S = p.rows.find((r) => r.status === 'quoted' && !r.adoptedSupplierId && r.procurement === '相見積' && p.quotes.filter((q) => q.rowId === r.id && !q.stale && q.unitPrice != null).length === 3 && /オムロン|三菱/.test(r.maker))
log('sample row', h.show(p, S.id), S.maker, S.model, 'targets', JSON.stringify(S.quoteTargets))
const A = await h.addRow('R080', 'メーカ変更リレー', 'G2R-1 DC24', 'オムロン', '相見積')
log('publish A →', await t.publish('1'))
await t.role('purchasing'); log('rule →', await h.setting('quoteCompleteRule', '全社', '完了条件'))
log('request all →', (await h.requestTo(null)).msg)
await t.press('6'); for (const [sid, pr, ld] of [['S1', 1500, 5], ['S2', 1450, 6], ['S3', 1600, 4]]) await h.q(A, sid, pr, ld); await t.press('Escape')
p = await t.proj(); log('A quoted', h.show(p, A), 'targets', JSON.stringify(p.rows.find((r) => r.id === A).quoteTargets))
// 設計: S の型式を変える / A のメーカをパナソニックに変える（因幡はパナソニックを扱わない）
await t.role('design'); await t.press('1')
await t.setCellKey(S.id, 'model', S.model + '-NEW'); await t.setCellKey(A, 'model', 'APAN1234'); await t.setCellKey(A, 'maker', 'パナソニック')
log('publish change →', await t.publish('1'))
p = await t.proj(); log('S after', h.show(p, S.id)); log('A after', h.show(p, A))
await t.role('purchasing')
// (a) S を因幡だけに再見積
const r1 = await h.requestTo('S1'); p = await t.proj(); log('S1 only →', r1.msg, JSON.stringify(r1.f.map((f) => [f.sup, f.ids.filter((x) => [S.id, A].includes(x))])))
log('S', h.show(p, S.id), '|', await h.status(S.id), 'targets', JSON.stringify(p.rows.find((r) => r.id === S.id).quoteTargets))
await t.press('6'); await h.q(S.id, 'S1', 999, 5); await t.press('Escape')
p = await t.proj(); const stS = p.rows.find((r) => r.id === S.id).status; log('S after S1 answer', h.show(p, S.id), '|', await h.status(S.id))
check('C2-1 (全社) 再見積を因幡だけに頼んだサンプルの行は、因幡 1 社の回答で見積済にならない（相見積先 3 社）', stS === 'quoting', stS)
const r2 = await h.requestTo('S2'); p = await t.proj(); log('S2 later →', r2.msg, JSON.stringify(r2.f.map((f) => [f.sup, f.ids.filter((x) => [S.id, A].includes(x))])))
check('C2-2 再見積の残りの商社（立花）に後から頼める', r2.f.some((f) => f.ids.includes(S.id)), r2.msg)
// (b) A: 相見積先すべてで再見積
p = await t.proj(); log('A before', h.show(p, A))
const r3 = await h.requestTo(null); p = await t.proj(); log('all →', r3.msg, JSON.stringify(r3.f.map((f) => [f.sup, f.ids.filter((x) => [A].includes(x))])))
log('A', h.show(p, A), '|', await h.status(A), 'targets', JSON.stringify(p.rows.find((r) => r.id === A).quoteTargets))
await t.press('6'); await h.q(A, 'S2', 2000, 5); await h.q(A, 'S3', 2100, 6); await t.press('Escape')
p = await t.proj(); const stA = p.rows.find((r) => r.id === A).status; log('A after S2,S3', h.show(p, A), '|', await h.status(A))
check('C2-3 (全社) メーカ変更後に再見積を頼んだ 2 社（立花・ミスミ）が答えたら見積済（パナソニックを扱わない因幡は待たない）', stA === 'quoted', stA)
const r4 = await h.requestTo(null); p = await t.proj(); log('all again →', r4.msg, JSON.stringify(r4.f.map((f) => [f.sup, f.ids.filter((x) => [A].includes(x))])))
check('C2-4 パナソニックを扱わない因幡にメーカ変更後の行の依頼書を出さない（§7 メーカで絞る）', !r4.f.some((f) => f.sup === '因幡電機' && f.ids.includes(A)), JSON.stringify(r4.f.map((f) => [f.sup, f.ids])))
await t.press('4'); log('purch 4 has A', (await t.viewRows()).includes(A))
summary(); await t.close()
