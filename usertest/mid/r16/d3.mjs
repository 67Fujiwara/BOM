// d3: 調達区分の切り替え（相見積 ↔ 指定商社 ↔ 客先指定品・指定先の変更）を状態ごとに
// main: A 見積中→指定商社 / B 選定済→指定商社（指定先は見積済の別の商社）/ C 指定商社の指定先を変更 / D 例外選定（PM 承認待ち）→指定商社 / F 客先指定品（選定済）→相見積
// formal: E 正式依頼中（相見積）→指定商社
import { launch, check, log, summary } from './lib.mjs'
import { helpers } from './h.mjs'
const mode = process.argv[2] ?? 'main'
const t = await launch(); const { page } = t; const h = helpers(t)
await t.open('design'); await t.press('1')
let p
const st = async (id) => { p = await t.proj(); return `${h.show(p, id)} | ${await h.status(id)} ball ${await h.ballOf(id)} case ${await h.caseOf(id)}` }
if (mode === 'main') {
  const A = await h.addRow('R080', '見積中から指定', 'G2R-1 DC24', 'オムロン', '相見積')
  const B = await h.addRow(A, '選定済から指定', 'G2R-2 DC24', 'オムロン', '相見積')
  const C = await h.addRow(B, '指定先を変える', 'G2R-1 DC12', 'オムロン', '指定商社', '立花エレテック')
  const D = await h.addRow(C, '例外選定から指定', 'G2R-2 DC12', 'オムロン', '相見積')
  const F = await h.addRow(D, '客先指定から相見積', 'G3NA-210B', 'オムロン', '客先指定品', '客先承認 KS-1')
  log('publish →', await t.publish('1'))
  await t.role('purchasing'); log('rule →', await h.setting('quoteCompleteRule', '全社', '完了条件'))
  const r1 = await h.requestTo(null); log('all →', r1.msg, JSON.stringify(r1.f.map((f) => [f.sup, f.ids.filter((x) => [A, B, C, D, F].includes(x))])))
  await t.press('6')
  await h.q(A, 'S1', 1500, 5)
  for (const [sid, pr, ld] of [['S1', 1000, 5], ['S2', 1100, 6], ['S3', 1200, 7]]) await h.q(B, sid, pr, ld)
  await h.q(C, 'S2', 800, 5)
  for (const [sid, pr, ld] of [['S1', 1000, 5], ['S2', 1100, 6], ['S3', 5000, 7]]) await h.q(D, sid, pr, ld)
  p = await t.proj(); const fsid = p.quotes.find((q) => q.rowId === F && !q.stale)?.supplierId; log('F asked', fsid)
  await h.q(F, fsid, 2000, 5); await t.press('Escape')
  await t.role('design'); await t.press('1')
  await t.goto(B); await t.press('a'); await page.waitForTimeout(80); log('B a →', await t.toast())
  const exc = await h.adoptPick(D, 3, '6', 'あえて'); log('D Shift+A 3 →', exc.toast)
  for (const id of [A, B, C, D, F]) log('before', await st(id))
  // 切り替え
  await t.setCellKey(A, 'procurement', '指定商社'); await t.setCellKey(A, 'designated', '立花エレテック')
  await t.setCellKey(B, 'procurement', '指定商社'); await t.setCellKey(B, 'designated', '立花エレテック')
  await t.setCellKey(C, 'designated', '因幡電機')
  await t.setCellKey(D, 'procurement', '指定商社'); await t.setCellKey(D, 'designated', '立花エレテック')
  await t.setCellKey(F, 'procurement', '相見積')
  log('publish switch →', await t.publish('1'))
  for (const id of [A, B, C, D, F]) log('after', await st(id))
  p = await t.proj()
  const rA = p.rows.find((r) => r.id === A), rB = p.rows.find((r) => r.id === B), rC = p.rows.find((r) => r.id === C), rD = p.rows.find((r) => r.id === D), rF = p.rows.find((r) => r.id === F)
  check('D3-1 見積中の相見積の行を指定商社（立花）にしたら、立花の回答待ちの見積中（購買のボール）', rA.status === 'quoting' && (await h.ballOf(A)) === 'purchasing', rA.status)
  check('D3-2 選定済（因幡）の行を、見積のある立花の指定商社にしたら、立花で選定済（指定先（固定））・発注数も立花の値', rB.status === 'selected' && rB.adoptedSupplierId === 'S2' && rB.adoptReason === '指定先（固定）', h.show(p, B))
  check('D3-3 指定先を因幡に変えた行は因幡の回答待ち（見積中）。立花の採用は外れる', rC.status === 'quoting' && !rC.adoptedSupplierId, h.show(p, C))
  check('D3-4 例外選定（ミスミ、PM 承認待ち）の行を立花の指定商社にしたら、例外選定の PM 承認待ちを残さない（立花で選定済）', !(rD.flags.pmPending && rD.flags.pmReason === '例外選定') && rD.adoptedSupplierId === 'S2', h.show(p, D))
  check('D3-5 客先指定品（選定済）を相見積にしたら、指定先（固定）の採用を外して相見積先に頼み直す', rF.adoptReason !== '指定先（固定）' && ['submitted', 'quoting', 'quoted'].includes(rF.status), h.show(p, F))
  await t.role('purchasing'); await t.press('4'); const p4 = await t.viewRows(); log('purch 4 has A/C', p4.includes(A), p4.includes(C), 'C status', await h.status(C))
  check('D3-10 指定先を因幡に変えた C（因幡にまだ頼んでいない）が購買の 4 に出る、または状態が回答待ちと分かる（「見積中 1/1」で全部答えたように見せない）', p4.includes(C) && !(await h.status(C)).includes('1/1'), `in4=${p4.includes(C)} ${await h.status(C)}`)
  await t.role('pm'); await t.press('7'); const pm7 = await t.viewRows(); log('PM 7 has', JSON.stringify([A, B, C, D, F].filter((x) => pm7.includes(x))))
  if (pm7.includes(D)) { await t.goto(D); await t.press('Enter'); await page.waitForTimeout(80); log('PM panel D', JSON.stringify(await t.panel())); await t.press('Escape'); const pk = process.argv[3] ?? 'y'; if (pk === 'y') log('PM y D →', JSON.stringify((await t.yes(D, '承認')).toast)); else log(`PM ${pk} D →`, JSON.stringify((await t.decide(D, pk, '理由')).toast)); p = await t.proj(); log('D decisions', JSON.stringify(p.decisions.filter((d) => d.rowId === D).map((d) => d.kind))); log('after y', await st(D)) }
  await t.role('purchasing'); const r2 = await h.requestTo(null); log('all after switch →', r2.msg, JSON.stringify(r2.f.map((f) => [f.sup, f.ids.filter((x) => [A, B, C, D, F].includes(x))])))
  check('D3-6 指定先を変えた C は因幡に依頼書が出る', r2.f.some((f) => f.sup === '因幡電機' && f.ids.includes(C)), JSON.stringify(r2.f.map((f) => [f.sup, f.ids.filter((x) => [A, B, C, D, F].includes(x))])))
  check('D3-7 相見積にした F は相見積先（まだ頼んでいない商社）に依頼書が出る', r2.f.filter((f) => f.ids.includes(F)).length >= 2, JSON.stringify(r2.f.map((f) => [f.sup, f.ids.includes(F)])))
  for (const id of [A, C, F]) log('after request', await st(id))
  await t.press('6'); await h.q(A, 'S2', 1300, 6); await t.press('Escape'); log('A after S2', await st(A))
  check('D3-8 指定商社にした A は立花の回答で選定済（指定先（固定））', (await t.row(A)).status === 'selected', await st(A))
} else if (mode === 'formal') {
  const E = await h.addRow('R080', '正式依頼中から指定', 'G2R-1 DC24', 'オムロン', '相見積')
  log('publish →', await t.publish('1'))
  await t.role('purchasing'); const r1 = await h.requestTo(null); log('all →', r1.msg)
  await t.press('6'); for (const [sid, pr, ld] of [['S1', 1000, 5], ['S2', 1100, 6], ['S3', 1200, 7]]) await h.q(E, sid, pr, ld); await t.press('Escape')
  await t.role('design'); await t.press('1'); await t.goto(E); await t.press('a'); await page.waitForTimeout(80); log('E a →', await t.toast())
  await t.role('purchasing'); const n0 = t.downloads.length; log('formal →', await t.requestFormal()); log('formal files', JSON.stringify((await h.files(n0)).map((f) => [f.sup, f.ids.includes(E)])))
  log('before', await st(E))
  await t.role('design'); await t.press('1'); await t.setCellKey(E, 'procurement', '指定商社'); await t.setCellKey(E, 'designated', '立花エレテック')
  log('publish switch →', await t.publish('1'))
  log('after', await st(E)); p = await t.proj(); const rE = p.rows.find((r) => r.id === E)
  const fq = p.quotes.filter((q) => q.rowId === E && !q.stale).map((q) => [q.supplierId, q.formalRequestNo ?? null])
  log('formal req nos', JSON.stringify(fq), 'reissue', rE.flags.reissue)
  await t.role('purchasing'); await t.press('8'); log('purch 8 has E', (await t.viewRows()).includes(E), 'header', (await t.status()).slice(0, 120))
  check('D3-9 正式依頼中（因幡）の行を立花の指定商社にしたら、因幡への正式依頼の取り下げが購買に分かる（8 の再発行対象・取り下げの案内）か、立花で選定済→正式見積を依頼できる', rE.adoptedSupplierId === 'S2' || rE.flags.reissue === true, h.show(p, E) + ' reissue=' + rE.flags.reissue)
  const n1 = t.downloads.length; log('formal again →', await t.requestFormal()); log('formal files', JSON.stringify((await h.files(n1)).map((f) => [f.sup, f.ids.includes(E)])))
  log('after formal again', await st(E))
}
summary(); await t.close()
