// e2: 3 社が回答済みの相見積の行を 指定商社 → 相見積 に戻す（U11-02 の修正「回答済みの商社には出さない」のあと）
import { launch, check, log, summary } from './lib.mjs'
import { helpers } from './h.mjs'
const t = await launch(); const { page } = t; const h = helpers(t)
await t.open('design'); await t.press('1')
const A = await h.addRow('R080', '戻すA', 'G2R-1 DC24', 'オムロン', '相見積')
log('publish →', await t.publish('1'))
await t.role('purchasing'); log('all →', (await h.requestTo(null)).msg)
await t.press('6'); for (const [sid, pr, ld] of [['S1', 1000, 5], ['S2', 1100, 6], ['S3', 1200, 7]]) await h.q(A, sid, pr, ld); await t.press('Escape')
let p = await t.proj(); log('A quoted', h.show(p, A), '|', await h.status(A))
await t.role('design'); await t.press('1')
await t.setCellKey(A, 'procurement', '指定商社'); await t.setCellKey(A, 'designated', '立花エレテック')
log('publish 指定 →', await t.publish('1'))
p = await t.proj(); log('A 指定', h.show(p, A), '|', await h.status(A))
await t.setCellKey(A, 'procurement', '相見積')
log('publish 相見積 →', await t.publish('1'))
p = await t.proj(); log('A back', h.show(p, A), '|', await h.status(A), 'ball', await h.ballOf(A), 'targets', JSON.stringify(p.rows.find((r) => r.id === A).quoteTargets))
await t.goto(A); await t.press('a'); await page.waitForTimeout(80); log('design a →', await t.toast())
await t.role('purchasing'); await t.press('9'); log('purch 9 has A', (await t.viewRows()).includes(A)); await t.press('4'); log('purch 4 has A', (await t.viewRows()).includes(A))
const rq = await h.requestTo(null); log('all again →', rq.msg, JSON.stringify(rq.f.map((f) => [f.sup, f.ids.includes(A)])))
p = await t.proj(); const r = p.rows.find((x) => x.id === A)
log('A after request', h.show(p, A), '|', await h.status(A), 'ball', await h.ballOf(A))
await t.role('design'); await t.press('1'); await t.goto(A); await t.press('a'); await page.waitForTimeout(80); const ta = await t.toast(); log('design a →', ta)
p = await t.proj()
check('E2-1 3 社が回答済みの行を相見積に戻したら、回答済みの見積で見積済に進むか、依頼して見積中になる（提出済で止まらない）', ['quoted', 'quoting', 'selected'].includes(r.status) && p.rows.find((x) => x.id === A).status === 'selected', `${r.status} / a: ${ta} / request: ${rq.msg}`)
await t.shot('e2')
summary(); await t.close()
