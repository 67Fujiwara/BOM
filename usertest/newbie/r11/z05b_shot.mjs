import { launch, fresh, T, makeLog, sel, gotoCol, ui, sleep, shot, row } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('z05b_shot')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '調達区分')
await page.keyboard.press('Enter'); await sleep(80); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await sleep(100)
const sel1 = await page.getByTestId('candidates').locator('[aria-selected="true"]').textContent()
const inp = await page.getByTestId('cell-editor').inputValue()
log('highlighted', sel1, 'input', inp)
await shot(page, 'z05b_procurement_enter_down2')
await page.keyboard.press('Enter'); await sleep(100)
log('R030 procurement after Enter', (await row(page, 'R030')).procurement, JSON.stringify((await row(page, 'R030')).working ?? null), 'toast', await T.toast(page))
await page.keyboard.press('ArrowUp'); await sleep(50)
await shot(page, 'z05b_after_enter')
save(errors); await browser.close()
