// ラウンド17: 購買の新人が、全社辞退になった行を「ほかの商社に依頼する」（ラウンド16 の新しい Ctrl+. の候補）で頼み直す（新人では初めて）。
// 設計が下書き R076 を公開 → 購買が概算見積を依頼（相見積先すべて）→ 3 社の辞退を取り込む → ステータスバーの案内 → Ctrl+. → 候補をマウスでクリック
// → 開いた「概算見積を依頼」でそのまま Enter（既定の「相見積先すべて」）→ 知らせのとおり ↓ で S4 を選んで Enter
import { launch, fresh, T, makeLog, sleep, shot, proj, setRole, sel, runPalette, clearToast } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog(process.env.LOGNAME2 || 'r25_alldeclined17')
const qs = async (id) => (await proj(page)).quotes.filter((q) => q.rowId === id && !q.stale).map((q) => `${q.supplierId}:${q.unitPrice ?? '-'}/${q.leadDays ?? '-'}`).join(' ')
const stCount = async () => { const by = {}; for (const r of (await proj(page)).rows) by[r.status] = (by[r.status] || 0) + 1; return JSON.stringify(by) }
const rowSt = async (id) => { const r = (await proj(page)).rows.find((x) => x.id === id); return `${r.id}:${r.status}:adopted=${r.adoptedSupplierId ?? '-'}:targets=${JSON.stringify(r.quoteTargets ?? null)}` }
async function importTsv(sid, tsv) {
  await clearToast(page)
  await runPalette(page, '見積回答を取り込む'); await sleep(150)
  const opts = await page.locator('.overlay .opt').allTextContents()
  const i = opts.findIndex((t) => t.includes(sid))
  for (let k = 0; k < i; k++) await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter'); await sleep(150)
  await page.locator('.overlay textarea').fill(tsv); await page.keyboard.press('Control+Enter'); await sleep(300)
  log(`  取り込み ${sid}: ${await T.toast(page)}`)
  if (await T.panel(page)) await page.keyboard.press('Escape')
}
await fresh(page); await sleep(150)
log('== 設計: 下書きの行を公開')
await page.keyboard.press('Control+Enter'); await sleep(250)
log('  panel: ' + ((await T.panelText(page)) ?? '-').slice(0, 200))
if (await T.panel(page)) { await page.keyboard.press('1'); await page.keyboard.press('Enter'); await sleep(300) }
log('  toast: ' + (await T.toast(page)))
log('  ' + (await rowSt('R076')))
await setRole(page, 'purchasing'); await sleep(200)
log('  status counts: ' + (await stCount()))
log('== 購買: 概算見積を依頼 → Enter')
await runPalette(page, '概算見積を依頼'); await sleep(150); await page.keyboard.press('Enter'); await sleep(400)
log('  toast: ' + (await T.toast(page)))
log('  ' + (await rowSt('R076')) + ' quotes ' + (await qs('R076')))
const model = (await proj(page)).rows.find((x) => x.id === 'R076').model
for (const sid of ['S1', 'S2', 'S3']) await importTsv(sid, `行ID\t型式\t単価\t納期\nR076\t${model}\t\t辞退`)
log('  ' + (await rowSt('R076')) + ' quotes ' + (await qs('R076')))
await sel(page, 'R076'); await sleep(200)
log('  hints: ' + (await T.hints(page)).slice(0, 300))
await shot(page, 'r25_declined_row')
log('== Ctrl+. の候補')
await page.keyboard.press('Control+.'); await sleep(200)
const items = await page.locator('.overlay .opt').allTextContents()
log('  options: ' + items.map((t) => t.replace(/\s+/g, ' ').slice(0, 120)).join(' || '))
await shot(page, 'r25_ctrldot')
const oi = items.findIndex((t) => t.includes('ほかの商社に依頼'))
if (oi < 0) { log('  「ほかの商社に依頼」が無い'); await page.keyboard.press('Escape') } else {
  await page.locator('.overlay .opt').nth(oi).click(); await sleep(300)
  log('  after click: panel=' + ((await T.panelText(page)) ?? '-').slice(0, 300) + ' | toast ' + (await T.toast(page)))
  await shot(page, 'r25_request_dialog')
  log('== そのまま Enter（相見積先すべて）')
  await page.keyboard.press('Enter'); await sleep(400)
  log('  toast: ' + (await T.toast(page)) + ' | panel ' + ((await T.panelText(page)) ?? '-').slice(0, 120))
  log('  ' + (await rowSt('R076')) + ' quotes ' + (await qs('R076')))
  if (await T.panel(page)) await page.keyboard.press('Escape')
  log('== もう一度 Ctrl+. →「ほかの商社に依頼」→ ↓ で S4 → Enter')
  await clearToast(page)
  await page.keyboard.press('Control+.'); await sleep(200)
  const it2 = await page.locator('.overlay .opt').allTextContents(); const o2 = it2.findIndex((t) => t.includes('ほかの商社に依頼'))
  if (o2 >= 0) {
    for (let k = 0; k < o2; k++) await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter'); await sleep(250)
    const opts = await page.locator('.overlay .opt').allTextContents()
    log('  依頼先: ' + opts.map((t) => t.replace(/\s+/g, ' ').slice(0, 60)).join(' | '))
    const i4 = opts.findIndex((t) => t.includes('S4'))
    for (let k = 0; k < i4; k++) await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter'); await sleep(400)
    log('  toast: ' + (await T.toast(page)) + ' | panel ' + ((await T.panelText(page)) ?? '-').slice(0, 120))
    log('  ' + (await rowSt('R076')) + ' quotes ' + (await qs('R076')))
    log('  project supplierIds: ' + JSON.stringify((await proj(page)).supplierIds))
    log('  status counts: ' + (await stCount()))
    log('  R001 quotes: ' + (await qs('R001')) + ' / ' + (await rowSt('R001')))
    await shot(page, 'r25_after_s4')
    log('  hints: ' + (await T.hints(page)).slice(0, 300))
  } else log('  2 回目: 候補なし ' + it2.join(' | ').slice(0, 200))
  if (await T.panel(page)) await page.keyboard.press('Escape')
}
log('== 設計に代替を相談（候補の 2 つ目）を見る: 別の新人は辞退の行で Ctrl+. → 設計に代替を相談')
save(errors); await browser.close()
