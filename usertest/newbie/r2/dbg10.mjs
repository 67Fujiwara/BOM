import { launch, fresh, T, runPalette, clearToast, shot } from './lib.mjs'
const { browser, page, errors } = await launch()
await fresh(page)
await runPalette(page, '新しいBOM'); for (let i = 0; i < 7; i++) await page.keyboard.press('Enter'); await page.keyboard.press('3'); await page.keyboard.press('Enter'); await page.keyboard.press('Enter'); await page.waitForTimeout(100)
console.log('created: view', await T.view(page), 'cursor', await T.cursor(page), 'rows', await T.rows(page), 'empty', await page.getByTestId('empty').innerText().catch(() => '-'))
await shot(page, 'r2_new_empty_project')
await clearToast(page)
await page.keyboard.press('n'); console.log('n:', await T.toast(page), 'cursor', await T.cursor(page))
await page.keyboard.press('Enter'); console.log('Enter:', await T.mode(page), await T.cursor(page))
await page.keyboard.type('リレー'); await page.keyboard.press('Enter')
console.log('after name: cursor', await T.cursor(page), 'rows', await T.rows(page), 'hints', await T.hints(page))
await page.keyboard.press('Control+Enter'); console.log('Ctrl+Enter:', await T.toast(page))
await page.keyboard.press('n'); console.log('n:', await T.toast(page), await T.cursor(page))
await page.keyboard.press('Control+.'); console.log('Ctrl+.:', await T.panelText(page), await T.toast(page))
await shot(page, 'r2_new_project_quickfix')
await browser.close(); console.log(errors)
