import { launch, fresh, T, store, sel, gotoCol, shot } from './lib.mjs'
const { browser, page, errors } = await launch()
await fresh(page); await page.keyboard.press('1')
const snap = async () => Object.fromEntries((await store(page))?.projects[0].rows.map((r) => [r.id, JSON.stringify({ n: r.name, m: r.model, mk: r.maker, w: r.working })]) ?? [])
await sel(page, 'R033'); await gotoCol(page, '部品名')
await page.keyboard.press('ArrowUp'); await page.keyboard.press('ArrowDown')
const b = await snap()
await page.keyboard.type('nut', { delay: 30 })
console.log('after typing nut: cursor', await T.cursor(page), 'mode', await T.mode(page), 'editor', await page.getByTestId('cell-editor').inputValue().catch(() => '-'))
await shot(page, 'r10_nut_before_enter')
await page.keyboard.press('Enter')
const a = await snap()
for (const k of Object.keys(a)) if (a[k] !== b[k]) console.log('changed', k, b[k], '->', a[k])
await browser.close(); console.log(errors)
