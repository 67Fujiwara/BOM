// ラウンド16: 変えた行だけ変更後を書く変更図（変えた行は変更後の型式・数量を両方書く）を新人がガイドで貼る → 知らせを読んで公開 → 購買で何行に見えるか。
// 知らせのとおり「新しい版の列に値を入れて貼り直す」とどうなるか
import { launch, T, makeLog, sleep, shot, proj, setRole, store } from './lib.mjs'
import { wizardPaste, rowsText } from './w15.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog(process.env.LOGNAME2 || 'r14_change_follow16')
const T1 = ['品名\t型式（旧）\t型式（新）\tメーカー\t数量（旧）\t数量（新）', 'リレー\tMY2N\tMY4N-D2\tオムロン\t2\t2', 'タイマ\tH3CR-A8\t\tオムロン\t1\t', 'ブレーカ\tNF32-SV\t\t三菱電機\t1\t', '端子台\tXW2B-20G4\t\tオムロン\t4\t'].join('\n')
log('== A 変えた行（リレー）だけ型式・数量の新を書いた変更図')
const pv = await wizardPaste(page, T1)
log('  preview: ' + pv.slice(0, 500))
await shot(page, 'r14_A_preview')
await page.keyboard.press('Enter'); await sleep(350)
let p = await proj(page); log(`  created rows=${p.rows.length}: ${rowsText(p)}`); log('  toast: ' + (await T.toast(page)))
await page.keyboard.press('Control+Enter'); await sleep(300); log('  Ctrl+Enter -> ' + (await T.toast(page)))
await setRole(page, 'purchasing'); await sleep(200)
p = await proj(page); log(`  購買: rows=${p.rows.length} ${p.rows.map((r) => `${r.id}:${r.name}:${r.status}`).join(' ')}`)
await shot(page, 'r14_A_purch')
log('== B 知らせのとおり「新しい版の列に値を入れて貼り直す」（変えない行の新にも旧と同じ値を書く）')
const T2 = ['品名\t型式（旧）\t型式（新）\tメーカー\t数量（旧）\t数量（新）', 'リレー\tMY2N\tMY4N-D2\tオムロン\t2\t2', 'タイマ\tH3CR-A8\tH3CR-A8\tオムロン\t1\t1', 'ブレーカ\tNF32-SV\tNF32-SV\t三菱電機\t1\t1', '端子台\tXW2B-20G4\tXW2B-20G4\tオムロン\t4\t4'].join('\n')
const pv2 = await wizardPaste(page, T2)
log('  preview: ' + pv2.slice(0, 300))
await page.keyboard.press('Enter'); await sleep(350)
p = await proj(page); log(`  created rows=${p.rows.length}: ${rowsText(p)}`)
log('== C 変えた行の数量は変えていないので数量（新）を空にした（正しい書き方）')
const T3 = T1.replace('リレー\tMY2N\tMY4N-D2\tオムロン\t2\t2', 'リレー\tMY2N\tMY4N-D2\tオムロン\t2\t')
await wizardPaste(page, T3); await page.keyboard.press('Enter'); await sleep(350)
p = await proj(page); log(`  created rows=${p.rows.length}: ${rowsText(p)}`)
const ws = await store(page); log('  projects: ' + ws.projects.map((x) => `${x.id}「${x.name}」rows=${x.rows.length}`).join(' / '))
save(errors); await browser.close()
