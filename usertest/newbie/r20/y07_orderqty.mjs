// 8 を開いて打った数が発注数に入る件の確認（行の状態・フラグ・警告）
import { launch, fresh, T, makeLog, shot, ui, typeReal, sleep, row, setRole } from './lib.mjs'
const { browser, page, errors } = await launch({ viewport: { width: 1024, height: 700 } })
const { log, save } = makeLog('y07_orderqty')
await fresh(page, 'purchasing')
const r0 = await row(page, 'R001'); log('R001 before', JSON.stringify({ st: r0.status, need: r0.qtyNeeded, pack: r0.packQty, oq: r0.orderQty, flags: r0.flags, adopted: r0.adoptedSupplierId }))
await page.keyboard.press('Alt+8'); await sleep(150)
log('cursor', await T.cursor(page), '| hints', await T.hints(page))
await shot(page, 'y07_8_open_1024')
await typeReal(page, '1500'); await sleep(50); await shot(page, 'y07_8_typing_1500'); await page.keyboard.press('Enter'); await sleep(150)
log('toast', await T.toast(page))
const r1 = await row(page, 'R001'); log('R001 after', JSON.stringify({ st: r1.status, need: r1.qtyNeeded, oq: r1.orderQty, flags: r1.flags }))
log('header', (await T.header(page)).replace(/\s+/g, ' ').slice(0, 300))
await page.keyboard.press('Escape'); await sleep(50)
// 1024 幅のステータスバー（指摘のある行）
await setRole(page, 'design'); await page.keyboard.press('Alt+4'); await sleep(150)
const items = await page.locator('.status .hints > *').evaluateAll((els) => els.map((e) => { const b = e.getBoundingClientRect(); return [e.textContent, Math.round(b.left), Math.round(b.right)] }))
log('statusbar 1024 (design 4):', JSON.stringify(items))
await shot(page, 'y07_status_1024_design4')
await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('ダーク'); await page.keyboard.press('Enter'); await sleep(200)
const items2 = await page.locator('.status .hints > *').evaluateAll((els) => els.map((e) => { const b = e.getBoundingClientRect(); return [e.textContent, Math.round(b.left), Math.round(b.right)] }))
log('statusbar 1024 dark:', JSON.stringify(items2))
await shot(page, 'y07_status_1024_dark')
save(errors); await browser.close()
