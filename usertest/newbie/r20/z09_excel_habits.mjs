// Excel の癖: Ctrl+S、打ってクリック、範囲選択して Delete、Ctrl+C/Ctrl+V、Ctrl+D、Esc、Ctrl+Z
import { launch, fresh, T, makeLog, sel, gotoCol, ui, typeReal, proj, sleep, shot, row } from './lib.mjs'
const { browser, context, page, errors } = await launch()
const { log, save } = makeLog('z09_excel_habits')
const st = async (tag) => { const u = await ui(page); log(`  [${tag}] mode=${u.mode} cur=${u.cursorRow}/${u.cursorCol} edit=${JSON.stringify(u.editValue)} panel=${u.panel} | toast: ${await T.toast(page)}`) }
const w = async (...ids) => { const o = {}; for (const id of ids) o[id] = (await row(page, id))?.working ?? null; return JSON.stringify(o) }
await page.evaluate(() => {})
log('== Ctrl+S（ナビ・編集中）')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '必要数')
await page.evaluate(() => { window.__prevented = []; window.addEventListener('keydown', (e) => { setTimeout(() => window.__prevented.push(e.key + ':' + e.defaultPrevented), 0) }, true) })
await page.keyboard.press('Control+s'); await sleep(100); await st('Ctrl+S nav')
await typeReal(page, '9'); await page.keyboard.press('Control+s'); await sleep(100); await st('9 Ctrl+S'); log('  ', await w('R030'))
log('  prevented', JSON.stringify(await page.evaluate(() => window.__prevented)))
log('== 打ってから別のセルをクリック')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '必要数'); await typeReal(page, '7')
await page.locator('[data-row-id="R033"] td').nth(5).click(); await sleep(150); await st('click R033'); log('  ', await w('R030', 'R033'))
log('== 打ってからサイドのビュー 3 をクリック')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '必要数'); await typeReal(page, '6')
await page.getByTestId('view-3').click(); await sleep(150); await st('click view 3'); log('  ', await w('R030'))
log('== Shift+↓ ×2 で範囲 → Delete（Excel で 3 セル消す）')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '備考')
await page.keyboard.press('Shift+ArrowDown'); await page.keyboard.press('Shift+ArrowDown'); await sleep(80); await st('Shift+↓↓')
await page.keyboard.press('Delete'); await sleep(100); await st('Delete'); log('  ', await w('R030', 'R031', 'R032'))
log('== 必要数 Shift+↓ ×2 → Delete')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '必要数')
await page.keyboard.press('Shift+ArrowDown'); await page.keyboard.press('Shift+ArrowDown'); await page.keyboard.press('Delete'); await sleep(100); await st('qty Delete'); log('  ', await w('R030', 'R031', 'R032'))
log('== Ctrl+C → ↓ → Ctrl+V（型式を下にコピー）')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '型式')
await page.keyboard.press('Control+c'); await sleep(100); await st('Ctrl+C'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Control+v'); await sleep(200); await st('↓ Ctrl+V'); log('  ', await w('R030', 'R031'))
log('== Ctrl+D（Excel の下へコピー）')
await fresh(page); await sel(page, 'R031'); await gotoCol(page, '型式')
await page.keyboard.press('Control+d'); await sleep(150); await st('Ctrl+D'); log('  ', await w('R030', 'R031'))
log('== 打った値を Esc（元の値に戻る？）')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '型式'); await typeReal(page, 'XYZ'); await page.keyboard.press('Escape'); await sleep(80); await st('XYZ Esc'); log('  ', await w('R030'))
log('== 編集中に Ctrl+Z（入力欄の取り消し）→ Enter')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '型式'); await page.keyboard.press('Enter'); await typeReal(page, 'ZZ'); await page.keyboard.press('Control+z'); await sleep(80); await st('Enter ZZ Ctrl+Z'); await page.keyboard.press('Enter'); await sleep(80); log('  ', await w('R030'))
log('== 打って Ctrl+Z（入力モード）')
await fresh(page); await sel(page, 'R030'); await gotoCol(page, '型式'); await typeReal(page, 'QQ'); await page.keyboard.press('Control+z'); await sleep(80); await st('QQ Ctrl+Z'); await page.keyboard.press('Enter'); await sleep(80); log('  ', await w('R030'))
await shot(page, 'z09_end')
save(errors); await browser.close()
