p = await proj(page)
log('after', JSON.stringify(p.rows.map((r) => ({ id: r.id, name: r.name, maker: r.maker, qty: r.qtyNeeded, st: r.status, pub: r.publishedRev }))))
log('status', (await T.status(page)).replace(/\s+/g, ' '))
