// リロードで画面の状態・Undo 履歴・ガイドの途中が戻るか（U-14 / U2-09 / V2-18 / U-05）
import { launch, fresh, T, makeLog, shot, sel, gotoCol, row, ui, palette } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('t04_reload')
const live = () => page.evaluate(async () => { const u = performance.getEntriesByType('resource').map((e) => e.name).find((n) => n.includes('/src/model/store.ts')); const s = (await import(u)).useStore.getState(); return { view: s.view, cursorRow: s.cursorRow, cursorCol: s.cursorCol, sort: s.sort, hiddenCols: s.hiddenCols.length, recent: s.recentCommands.slice(0, 3), wizardDraft: s.wizardDraft, undoN: Object.values(s.undo).reduce((a, v) => a + v.length, 0) } })
const ss = () => page.evaluate(() => { const u = JSON.parse(sessionStorage.getItem('bom-pro.ui') ?? 'null'); const h = JSON.parse(sessionStorage.getItem('bom-pro.history') ?? 'null'); return { ui: u && { view: u.view, cursorRow: u.cursorRow, cursorCol: u.cursorCol, sort: u.sort, hiddenCols: u.hiddenCols?.length, wizardDraft: !!u.wizardDraft }, undoN: h ? Object.values(h.undo).reduce((a, v) => a + v.length, 0) : null } })
await fresh(page)
await page.keyboard.press('5'); await page.keyboard.press('1')
await sel(page, 'R040'); await gotoCol(page, 'メーカ')
await page.keyboard.press('Enter'); await page.keyboard.press('Control+a'); await page.keyboard.type('UNDOTEST'); await page.keyboard.press('Enter')
await sel(page, 'R041'); await gotoCol(page, '型式'); await page.keyboard.press('s')
await page.keyboard.press('c'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press(' '); await page.keyboard.press('Escape')
await palette(page, '新しいBOM'); await page.keyboard.press('Enter'); await page.getByTestId('wizard-id').fill('DRAFT-9'); await page.keyboard.press('Escape')
await page.waitForTimeout(800)
log('before reload: live', JSON.stringify(await live()))
log('before reload: sessionStorage', JSON.stringify(await ss()))
await page.reload(); await page.getByTestId('grid').waitFor(); await page.waitForTimeout(800)
log('after reload: live', JSON.stringify(await live()))
log('after reload: sessionStorage', JSON.stringify(await ss()))
await page.keyboard.press('Control+z'); await page.waitForTimeout(100)
log('Ctrl+Z after reload:', await T.toast(page), 'R040 working', JSON.stringify((await row(page, 'R040')).working))
await palette(page, '新しいBOM'); await page.keyboard.press('Enter'); await page.waitForTimeout(100)
log('wizard after reload id', await page.getByTestId('wizard-id').inputValue().catch(() => '-'), 'toast', await T.toast(page))
await page.keyboard.press('Escape')
// 次の操作で sessionStorage の履歴が上書きされるか
await sel(page, 'R042'); await gotoCol(page, 'メーカ'); await page.keyboard.press('Enter'); await page.keyboard.press('Control+a'); await page.keyboard.type('X2'); await page.keyboard.press('Enter'); await page.waitForTimeout(800)
log('after next edit: sessionStorage', JSON.stringify(await ss()))
await shot(page, 't08_after_reload')

// 追加: ガイドの 8 で貼り付けた途中でリロード → 開き直す
await palette(page, '新しいBOM'); await page.keyboard.press('Enter'); await page.waitForTimeout(80)
for (let i = 0; i < 7; i++) { await page.keyboard.press('Enter'); await page.waitForTimeout(60) }
log('wizard step text', (await T.panelText(page))?.slice(0, 160))
await page.keyboard.press('1'); await page.waitForTimeout(60); await page.keyboard.press('Enter'); await page.waitForTimeout(80)
const ta = page.locator('.overlay textarea'); log('textarea?', await ta.count())
if (await ta.count()) await ta.fill('部品名\t型式\tメーカ\t数量\nリレー\tMY4N\tオムロン\t4')
await page.waitForTimeout(800)
await page.reload(); await page.getByTestId('grid').waitFor(); await page.waitForTimeout(500)
log('after reload panel', await T.panel(page))
await palette(page, '新しいBOM'); await page.keyboard.press('Enter'); await page.waitForTimeout(150)
log('wizard reopened:', (await T.panelText(page))?.slice(0, 300), '| textarea', await page.locator('.overlay textarea').inputValue().catch(() => '-'))
await shot(page, 't04_wizard_after_reload')
await page.keyboard.press('Escape')
// 追加: Undo → リロード → Ctrl+Y
await sel(page, 'R043'); await gotoCol(page, 'メーカ'); await page.keyboard.press('Enter'); await page.keyboard.press('Control+a'); await page.keyboard.type('REDOTEST'); await page.keyboard.press('Enter')
await page.keyboard.press('Control+z'); await page.waitForTimeout(800)
await page.reload(); await page.getByTestId('grid').waitFor(); await page.waitForTimeout(500)
await page.keyboard.press('Control+y'); await page.waitForTimeout(150)
log('Ctrl+Y after reload:', await T.toast(page), 'R043', JSON.stringify((await row(page, 'R043')).working))
save(errors)
await browser.close()
