// ラウンド13: 「未定」「TBD」「-」の型式・メーカーの行（新人の BOM によくある）を取り込んで公開できるか、購買にどう見えるか
import { launch, fresh, T, makeLog, shot, sel, gotoCol, ui, typeReal, proj, sleep, palette, setRole, runPalette } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('v09_mitei')
await fresh(page); await palette(page, '新しいBOM'); await page.keyboard.press('Enter'); await page.getByTestId('wizard').waitFor()
for (let i = 0; i < 7; i++) await page.keyboard.press('Enter')
await page.keyboard.press('1'); await sleep(80)
await page.getByTestId('wizard-paste').fill('品名\t型式\tメーカー\t数量\nリレー\tMY4N-D2\tオムロン\t4\nヒューズ\t未定\t未定\t2\n端子台\tTBD\tTBD\t3\nスペーサ\t-\t-\t8\nケーブル\t(未定)\t（検討中）\t1')
await page.keyboard.press('Control+Enter'); await sleep(200)
log('preview: ' + (await page.getByTestId('wizard-preview').innerText()).replace(/\s+/g, ' ').slice(0, 600))
await page.keyboard.press('Enter'); await sleep(300)
log('created toast: ' + (await T.toast(page)))
const p0 = await proj(page)
log('rows: ' + p0.rows.map((r) => `${r.id}:${r.name}/${r.model}/${r.maker}/${r.qtyNeeded}`).join(' '))
log('status bar: ' + (await page.getByTestId('header').innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 200))
await page.keyboard.press('Alt+4'); await sleep(150)
log('4 要確認 rows: ' + (await page.getByTestId('row').evaluateAll((els) => els.map((e) => e.getAttribute('data-row-id')).join(','))))
await page.keyboard.press('Control+Enter'); await sleep(200); log('Ctrl+Enter: ' + (await T.toast(page)) + ' | panel ' + (await T.panelText(page)))
if (await T.panel(page)) { await page.keyboard.press('1'); await page.keyboard.press('Enter'); await sleep(200); log('  -> ' + (await T.toast(page))) }
const p1 = await proj(page)
log('after: ' + p1.rows.map((r) => `${r.id}:${r.status}:${r.model}/${r.maker}`).join(' '))
await shot(page, 'v09_mitei_published')
await setRole(page, 'purchasing'); await sleep(150)
log('purch view rows: ' + (await page.getByTestId('row').evaluateAll((els) => els.map((e) => e.innerText.replace(/\s+/g, ' ').slice(0, 80)).join(' || '))))
// 表で型式に「未定」と打つ
await setRole(page, 'design'); await fresh(page); await sel(page, 'R030'); await gotoCol(page, '型式'); await page.keyboard.press('Enter'); await page.keyboard.press('Control+a'); await page.keyboard.insertText('未定'); await page.keyboard.press('Enter'); await sleep(150)
log('typed 未定 in R030 型式: toast=' + (await T.toast(page)) + ' cell=' + (await page.locator('[data-row-id="R030"] td[data-col="model"]').innerText().catch(() => '-')))
await page.keyboard.press('Control+Enter'); await sleep(200); log('Ctrl+Enter: ' + (await T.toast(page)) + ' | panel ' + (await T.panelText(page))?.slice(0, 100))
save(errors); await browser.close()
