// ラウンド23 n06: 区切りの選び方（見出しの語が並ぶ行ができるほう）。表題のコンマ、回路記号のコンマ、セルの中のタブ、英語の見出し、両方で見出しになる場合
import fs from 'node:fs'
import { loadParsers } from './parselib.mjs'
const { old, neu } = await loadParsers(process.env.OLD || '68e45f7')
const tab = (rows) => rows.map((r) => r.join('\t')).join('\n')
const csv = (rows) => rows.map((r) => r.map((c) => (/[",\n]/.test(c) ? '"' + c.replace(/"/g, '""') + '"' : c)).join(',')).join('\n')
const parts = [['リレー', 'MY4N-D2', 'オムロン', '4'], ['タイマ', 'H3CR-A8', 'オムロン', '1'], ['端子台', 'XW2B-20G4', 'オムロン', '4'], ['ヒューズ', 'F-5A', 'ミツミ', '3']]
const H = ['品名', '型式', 'メーカー', '数量']
const cases = []
const add = (name, text, expectRows, expectDelim) => cases.push({ name, text, expectRows, expectDelim })
// 1 TSV＋コンマ入りの表題を N 行
for (const n of [1, 3, 6, 10, 20]) add(`TSV 表題コンマ入り${n}行`, [...Array.from({ length: n }, (_, i) => `案件名: 制御盤A, 客先: ABC, 担当: 田中, 日付: 2026-10-${10 + (i % 9)}, 備考なし`), tab([H, ...parts])].join('\n'), 4, 'tab')
// 2 TSV＋回路記号のコンマ
add('TSV 回路記号コンマ多', tab([['品名', '型式', '回路記号', '数量'], ['抵抗', 'R-10k', 'R1,R2,R3,R4,R5,R6', '6'], ['コンデンサ', 'C-100u', 'C1,C2,C3,C4,C5', '5'], ['IC', 'NE555', 'U1,U2,U3,U4,U5,U6,U7', '7'], ['LED', 'LED-R', 'D1,D2,D3,D4,D5', '5']]), 4, 'tab')
// 3 TSV 短い（部品2行）＋説明コンマ
add('TSV 部品2行＋説明', ['この表は A, B, C, D を含みます', '改訂履歴: 1, 2, 3, 4', '承認: 部長, 課長, 係長', '作成: 田中, 鈴木', tab([H, parts[0], parts[1]]), 'a,b,c,d,e', '1,2,3,4,5'].join('\n'), 2, 'tab')
// 4 CSV＋セルの中のタブ
add('CSV セルにタブ', csv([H.concat(['備考']), ...parts.map((p, i) => p.concat([i === 1 ? '盤内\t上段' : '']))]), 4, 'comma')
add('CSV 見出しにタブ', csv([['品名\t(日本語)', '型式', 'メーカー', '数量'], ...parts]), 4, 'comma')
// 5 KiCad 風 英語
add('KiCad TSV', tab([['Reference', 'Value', 'Footprint', 'Qty'], ['R1,R2', '10k', '0603', '2'], ['C1', '100n', '0603', '1']]), 2, 'tab')
add('KiCad CSV 引用', csv([['Reference', 'Value', 'Footprint', 'Qty'], ['R1,R2', '10k', '0603', '2'], ['C1', '100n', '0603', '1']]), 2, 'comma')
add('Designator TSV', tab([['Designator', 'Comment', 'Footprint', 'Quantity'], ['R1, R2, R3', '10k', '0603', '3'], ['C1, C2', '100n', '0603', '2']]), 2, 'tab')
// 6 両方で見出し：タブ区切りの見出し＋コンマ区切りの見出し風の表題
add('TSV 見出し風の表題', ['品名,型式,数量 の順に記入', tab([H, ...parts])].join('\n'), 4, 'tab')
add('CSV 見出し＋タブ見出し風の表題', ['品名\t型式\t数量 の順に記入', csv([H, ...parts])].join('\n'), 4, 'comma')
// 7 見出しのセルにコンマ
add('TSV 見出しにコンマ', tab([['品名', '型式(旧, 新)', 'メーカー', '数量(個, 台)'], ...parts]), 4, 'tab')
// 8 コンマ区切り＋表題にタブ
add('CSV 表題にタブ', ['案件名\t制御盤A\t客先\tABC', csv([H, ...parts])].join('\n'), 4, 'comma')
// 9 タブ区切りの表題がコンマ区切りのように見える
add('TSV 日付に千位コンマ', tab([H.concat(['単価']), ...parts.map((p, i) => p.concat([['1,200', '3,500', '800', '12,000'][i]]))]), 4, 'tab')
add('CSV 千位引用', csv([H.concat(['単価']), ...parts.map((p, i) => p.concat([['1,200', '3,500', '800', '12,000'][i]]))]), 4, 'comma')
// 10 見出しなし
add('TSV 見出しなしコンマ入り', tab(parts.map((p, i) => [p[0], p[1], 'A,B', p[3]])), 4, 'tab')
add('CSV 見出しなし', csv(parts), 4, 'comma')
// 11 全部コンマ入りの備考＋タブ
add('TSV 備考にコンマ全行', tab([H.concat(['備考']), ...parts.map((p) => p.concat(['a,b,c,d,e,f']))]), 4, 'tab')
// 12 表題＋EDA
add('TSV EDA タイトルブロック', ['Project: Board A, Rev: 2, Date: 2026-10-24', 'Company: ABC Co., Ltd.', 'Generated by Eeschema, version 7.0, on 2026-10-24', '', tab([['Item', 'Reference(s)', 'Value', 'Qty'], ['1', 'R1,R2', '10k', '2'], ['2', 'C1', '100n', '1']])].join('\n'), 2, 'tab')
add('TSV 表題5行にコンマ6個', [...Array(5).fill('株式会社ABC, 設計部, 第一課, 担当者: 山田, 田中, 鈴木'), tab([H, ...parts])].join('\n'), 4, 'tab')
add('TSV 全角コンマ', tab([H.concat(['備考']), ...parts.map((p) => p.concat(['A，B，C']))]), 4, 'tab')
add('セミコロン区切り', [H, ...parts].map((r) => r.join(';')).join('\n'), 4, 'none?')
const out = []
let bad = 0
for (const c of cases) {
  const o = old.parseBomPaste(c.text), r = neu.parseBomPaste(c.text)
  const okN = r.rows.length === c.expectRows && (c.expectDelim.endsWith('?') || r.delimiter === c.expectDelim)
  const okO = o.rows.length === c.expectRows && (c.expectDelim.endsWith('?') || o.delimiter === c.expectDelim)
  out.push(`${okN ? 'OK ' : 'NG '}${okO ? '(old OK)' : '(old NG)'} ${c.name}: new delim=${r.delimiter} rows=${r.rows.length} / old delim=${o.delimiter} rows=${o.rows.length} / 期待 ${c.expectDelim} ${c.expectRows}`)
  if (!okN) bad++
}
fs.writeFileSync('results/n06_delim.out', out.join('\n') + '\n\nNG ' + bad + '\n')
console.log(out.join('\n'))
