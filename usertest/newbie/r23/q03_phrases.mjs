// ラウンド22 q03: 備考の言い回し（一部削除・不要の為削除・全削除・一式削除・取外し可能・撤去スペース確保・文の中の削除/撤去/取外し）を変更図と、ふつうの BOM の両方で
import fs from 'node:fs'
import { loadParsers, T, lab } from './parselib.mjs'
const { old, neu } = await loadParsers()
const chg = (n) => T(`品名｜型式（旧）｜型式（新）｜メーカー｜数量｜備考
リレー｜MY2N｜MY4N-D2｜オムロン｜4｜
部品1｜P-10｜｜オムロン｜1｜${n}
端子台｜XW2B-20G4｜｜オムロン｜4｜`)
const ord = (n) => T(`品名｜型式｜メーカー｜数量｜備考
リレー｜MY4N-D2｜オムロン｜4｜
部品1｜P-10｜オムロン｜1｜${n}
端子台｜XW2B-20G4｜オムロン｜4｜`)
const kc = (res) => { const l = res.rows.map(lab); return l.includes('P-10:1?') ? 'ASK' : l.includes('P-10:1') ? 'KEEP' : 'DEL' }
const D = ['一部削除', '一部撤去', '一部を削除', '半分削除', '2個のうち1個削除', '1個削除', '1個減らす', '不要の為削除', '不要につき削除', '不要なので削除', '不要なため削除', '不要ゆえ削除', '不要で削除', '使わないので削除', '使用しないので削除', '全削除', '全て削除', 'すべて削除', '全数削除', '全部削除', '全撤去', '一式削除', '一式撤去', '一式取外し', 'ユニットごと削除', '旧品削除', 'ケーブル類削除', 'このユニット削除', '本品削除', '当該品削除', '当部品削除', '該当部品を削除', 'この部品は削除', 'この部品を削除してください', 'この部品は削除でお願いします', 'こちら削除', 'こちらは削除', 'これは削除', '本ユニット不要', '削除対象', '削除対象品', '削除予定', '削除する予定', '削除予定品']
const K = ['取外し可能', '取り外し可能', '取外し可', '撤去スペース確保', '撤去スペース要', '撤去しやすいこと', '撤去が容易', '取外し容易', '取外し工具: ドライバ', '取外し方法は別紙', '取外し手順は別紙', '取外し時は注意', '削除不要', '削除は不要', '削除しないこと', '削除禁止', '削除しないでください', '削除しないで', '削除はしないでください', '削除は行わない', '削除は不可', '削除不可', '削除できない', '削除できません', '削除してはダメ', '撤去不可', '撤去しない', '撤去はしない', '撤去は不要', '撤去不要', '撤去禁止', '取外し不可', '取外し禁止', '取外ししない', '取外し不要', '廃止しない', '廃止は不要', '廃止予定なし', '廃止不可', '廃止予定はない', '廃止の予定なし', '削除の予定なし', '削除の予定はない', '削除予定なし', '削除予定はなし', '削除予定無し', '削除予定ではない', '削除予定じゃない']
const A = ['削除してもよい', '削除してよいか確認', '削除しても可', '削除可', '削除でも可', '削除できる', '削除可能', '削除可能性あり', '削除の可能性', '削除の方向', '削除方向で調整', '削除かも', '削除かも？', '削除検討', '削除を検討', '削除検討中', '削除要確認', '削除について確認中', '削除相談', '削除の相談', '削除希望', '削除したい', '削除したいです', '削除したほうがよい', '削除したほうがいい', '削除すべき', '削除すべきか', '削除すべきか確認', '削除が望ましい', '削除推奨', '削除でよいか', '削除でいいか', '削除でいい？', '削除でOK？']
const rowsOut = []
let bad = { 'D→notDEL': [], 'K→DEL': [], 'K→ASK': [], 'A→DEL': [], 'A→KEEP': [], ordChanged: [] }
for (const [m, list] of [['D', D], ['K', K], ['A', A]]) for (const w of list) {
  const t = chg(w), o = kc(old.parseBomPaste(t)), r = kc(neu.parseBomPaste(t))
  rowsOut.push(`${m} 「${w}」 chg old=${o} new=${r}`)
  if (m === 'D' && r !== 'DEL') bad['D→notDEL'].push(`${w}=${r}(old=${o})`)
  if (m === 'K' && r === 'DEL') bad['K→DEL'].push(`${w}(old=${o})`)
  if (m === 'K' && r === 'ASK') bad['K→ASK'].push(`${w}(old=${o})`)
  if (m === 'A' && r === 'DEL') bad['A→DEL'].push(`${w}(old=${o})`)
  if (m === 'A' && r === 'KEEP') bad['A→KEEP'].push(`${w}(old=${o})`)
  // ふつうの BOM: 旧／新が無いので備考は何を書いても全部残るはず
  const to = ord(w)
  const a = JSON.stringify(old.parseBomPaste(to).rows.map(lab)), b = JSON.stringify(neu.parseBomPaste(to).rows.map(lab))
  if (a !== b || neu.parseBomPaste(to).rows.length !== 3) bad.ordChanged.push(`${w}: old=${a} new=${b}`)
}
console.log(JSON.stringify(bad, null, 1))
fs.writeFileSync('results/q03_phrases.out', rowsOut.join('\n') + '\n\nSUMMARY ' + JSON.stringify(bad, null, 1) + '\n')
