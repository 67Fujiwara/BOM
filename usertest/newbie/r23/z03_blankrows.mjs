import { launch, fresh, T, makeLog, shot, proj, palette, sleep, ui } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('z03_blankrows')
const D = '/home/user/BOM/usertest/newbie/r23/files11/'
await fresh(page); await palette(page, '新しいBOM'); await page.keyboard.press('Enter'); await page.getByTestId('wizard').waitFor()
for (let i = 0; i < 7; i++) await page.keyboard.press('Enter')
await page.keyboard.press('2'); await sleep(80)
await page.getByTestId('wizard-file').setInputFiles(D + 'g3_three_pages.xlsx'); await sleep(1500)
await page.keyboard.press('Enter'); await sleep(200); await page.keyboard.press('Enter'); await sleep(300)
let p = await proj(page)
log('after create', p.rows.map((r) => `${r.id}:${r.name || '(空)'}:${r.status}`).join(' '))
log('rows on screen', await T.rows(page), 'header', (await T.header(page)).slice(0, 200))
await shot(page, 'z03_after_create')
await page.keyboard.press('Control+Enter'); await sleep(300); log('Ctrl+Enter', await T.toast(page), await T.panelText(page))
p = await proj(page)
log('after publish', p.rows.map((r) => `${r.id}:${r.name || '(空)'}:${r.status}:${r.hidden ? 'hidden' : ''}`).join(' '))
log('rows on screen', await T.rows(page))
await page.keyboard.press('Alt+4'); await sleep(200); log('view4 rows', await T.rows(page), await page.getByTestId('row').evaluateAll((els) => els.map((e) => e.getAttribute('data-row-id')).join(',')))
await shot(page, 'z03_after_publish')
save(errors); await browser.close()
