import { launch, fresh, T, sel, ui, proj, shot } from './lib.mjs'
const { browser, page } = await launch()
await fresh(page, 'purchasing'); await page.keyboard.press('1'); await sel(page, 'R030'); await page.keyboard.press('Shift+I'); await page.keyboard.press('k'); await page.waitForTimeout(80)
await page.keyboard.insertText('型式の末尾が抜けています'); await page.waitForTimeout(80)
console.log('before', await page.locator('.overlay textarea, .overlay input').first().inputValue())
await shot(page, 'dbg_ctrlk_issue_before')
await page.keyboard.press('Control+k'); await page.waitForTimeout(80); console.log('palette', await T.panel(page))
await page.keyboard.press('Escape'); await page.waitForTimeout(80); console.log('after esc', await T.panel(page))
await page.keyboard.press('Shift+I'); await page.keyboard.press('k'); await page.waitForTimeout(80)
console.log('after reopen', JSON.stringify(await page.locator('.overlay textarea, .overlay input').first().inputValue()))
await shot(page, 'dbg_ctrlk_issue_after')
await page.keyboard.press('Escape')
// 設計の r
await fresh(page); await page.keyboard.press('1'); await sel(page, 'R030'); await page.keyboard.press('r'); await page.waitForTimeout(100)
console.log('r panel', (await T.panelText(page))?.slice(0, 200))
await page.getByTestId('prompt-text').fill('S-T21 AC200V'); await page.keyboard.press('Control+k'); await page.waitForTimeout(80); await page.keyboard.press('Escape'); await page.waitForTimeout(80)
await page.keyboard.press('r'); await page.waitForTimeout(100)
console.log('r reopen', (await T.panelText(page))?.slice(0, 100), JSON.stringify(await page.getByTestId('prompt-text').inputValue().catch(() => '-')))
await browser.close()
