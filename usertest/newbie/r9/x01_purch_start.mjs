import { launch, fresh, T, makeLog, shot, sel, gotoCol, ui, typeReal, proj, sleep, diff, row } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('x01_purch_start')
const st = async (tag) => { const u = await ui(page); log(`  [${tag}] role=${u.role} mode=${u.mode} view=${u.view} cur=${u.cursorRow}/${u.cursorCol} edit=${JSON.stringify(u.editValue)} panel=${u.panel} | cursorbar=${await T.cursor(page)} | hints: ${await T.hints(page)} | toast: ${await T.toast(page)}`) }
log('== 購買: 役割ボタン → 直後の状態 → 8')
await fresh(page, 'purchasing'); await sleep(200); await st('after role')
await page.keyboard.press('8'); await sleep(150); await st('8')
await page.keyboard.press('6'); await sleep(150); await st('6')
await shot(page, 'x01_purch_start_8')
log('== 購買: 役割ボタン → ↓ → 状態')
await fresh(page, 'purchasing'); await sleep(200)
await page.keyboard.press('ArrowDown'); await sleep(150); await st('↓')
await page.keyboard.press('Enter'); await sleep(150); await st('Enter')
await page.keyboard.press('Escape'); await sleep(150); await st('Esc')
log('== 購買: ロード時（リロード後に購買のまま）')
await page.reload(); await page.getByTestId('grid').waitFor(); await page.locator('.gridwrap').focus(); await sleep(300); await st('reload')
await page.keyboard.press('8'); await sleep(150); await st('8')
log('== PM: 役割ボタン直後')
await fresh(page, 'pm'); await sleep(200); await st('after role')
log('== 設計: 起動直後')
await fresh(page); await sleep(200); await st('start')
await page.keyboard.press('9'); await sleep(150); await st('9')
log('== 設計 → 購買（ボタン）→ 設計')
await page.keyboard.press('ArrowDown'); await sleep(100); await st('↓')
await page.getByTestId('role-purchasing').click(); await page.locator('.gridwrap').focus(); await sleep(200); await st('purch')
await page.keyboard.press('6'); await sleep(150); await st('6')
save(errors); await browser.close()
