// S04: 順番・役割を間違える新人（約15人）
import { launch, fresh, T, makeLog, shot, sel, gotoCol } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('s04_order')
try {
  await fresh(page)
  // カーソル無しで a / Shift+I / Space / Enter / x / r / o
  for (const k of ['a', 'Shift+I', 'x', 'r', 'o', 'Shift+A', 'Alt+a', 'w', 'Control+.', 'Shift+R', 'Shift+X', 'y', 'Shift+Y']) {
    await fresh(page)
    await page.keyboard.press(k)
    await page.waitForTimeout(30)
    log(`no-cursor ${k}: cursor`, await T.cursor(page), 'panel', await T.panel(page), 'toast', await T.toast(page), 'mode', await T.mode(page), 'rows', await T.rows(page))
    await page.keyboard.press('Escape')
  }
  await fresh(page)
  // 見積前の行（提出済・下書き）に a
  const statuses = await page.evaluate(() => [...document.querySelectorAll('[data-row-id]')].map((tr) => tr.dataset.rowId + ':' + (tr.querySelector('.status-pill')?.textContent ?? '')))
  log('statuses:', statuses.join(' '))
  const pick = (s) => statuses.find((x) => x.endsWith(':' + s))?.split(':')[0]
  const submitted = pick('提出済'), draft = pick('下書き'), quoting = pick('見積中'), quoted = pick('見積済'), selected = pick('選定済'), ordered = pick('発注済'), formalReq = pick('正式依頼中')
  log('picked', { submitted, draft, quoting, quoted, selected, ordered, formalReq })
  for (const [label, id] of [['submitted', submitted], ['draft', draft], ['quoting', quoting], ['selected', selected], ['ordered', ordered], ['formalReq', formalReq]]) {
    if (!id) continue
    await sel(page, id)
    await page.keyboard.press('a')
    log(`a on ${label} ${id}: toast`, await T.toast(page))
    await page.keyboard.press('Shift+A')
    log(`Shift+A on ${label} ${id}: panel`, await T.panel(page), 'toast', await T.toast(page))
    await page.keyboard.press('Escape')
    await page.keyboard.press('Alt+a')
    log(`Alt+A on ${label} ${id}: panel`, await T.panel(page), 'toast', await T.toast(page))
    await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
  }
  // 設計が Shift+I（購買の操作）
  await sel(page, quoted ?? 'R020')
  await page.keyboard.press('Shift+I')
  log('design Shift+I: panel', await T.panel(page), 'toast', await T.toast(page))
  if (await T.panel(page)) {
    await page.keyboard.press('k')
    await page.getByTestId('issue-text').fill('設計が自分に指摘')
    await page.keyboard.press('Enter')
    log('design raised issue: toast', await T.toast(page), 'status', (await T.status(page)).slice(0, 100))
    await page.keyboard.press('Control+Enter')
    log('design Ctrl+Enter after self-issue: toast', await T.toast(page), 'panel', await T.panel(page))
    await page.keyboard.press('Escape')
  }
  // エラーのまま Ctrl+Enter（設計）
  await fresh(page)
  await page.keyboard.press('Control+Enter')
  log('design Ctrl+Enter with errors: toast', await T.toast(page), 'panel', await T.panel(page))
  await shot(page, 's04_publish_blocked')
  await page.keyboard.press('Escape')
  // 設計が y / Shift+Y
  await sel(page, 'R020')
  await page.keyboard.press('y')
  log('design y:', await T.toast(page))
  await page.keyboard.press('Shift+Y')
  log('design Shift+Y:', await T.toast(page))
  // 購買で型式を Enter 編集・文字打ち・Shift+Enter・Shift+Delete・r
  await fresh(page, 'purchasing')
  await sel(page, 'R020')
  await gotoCol(page, '型式')
  await page.keyboard.press('Enter')
  log('purchasing Enter on model: mode', await T.mode(page), 'toast', await T.toast(page))
  await page.keyboard.press('z')
  log('purchasing type z on model: mode', await T.mode(page), 'toast', await T.toast(page))
  await page.keyboard.press('Shift+Enter')
  log('purchasing Shift+Enter: toast', await T.toast(page), 'rows', await T.rows(page))
  await page.keyboard.press('Shift+Delete')
  log('purchasing Shift+Delete: toast', await T.toast(page))
  await page.keyboard.press('r')
  log('purchasing r: toast', await T.toast(page), 'mode', await T.mode(page))
  await page.keyboard.press('a')
  log('purchasing a: toast', await T.toast(page))
  await page.keyboard.press('Control+Enter')
  log('purchasing Ctrl+Enter nothing: toast', await T.toast(page))
  await page.keyboard.press('Delete')
  log('purchasing Delete on model: toast', await T.toast(page))
  // 購買が単価を打つ（見積列は表示されている？）
  const ths = await page.locator('table.grid th').allTextContents()
  log('purchasing view1 columns:', ths.join('|'))
  await page.keyboard.press('9')
  const ths9 = await page.locator('table.grid th').allTextContents()
  log('purchasing view9 columns:', ths9.join('|'))
  await page.keyboard.press('6')
  const ths6 = await page.locator('table.grid th').allTextContents()
  log('purchasing view6 columns:', ths6.join('|'), 'rows', await T.rows(page))
  await shot(page, 's04_view6_purchasing')
  // 6 で単価セルに数字を打つ
  await page.keyboard.press('ArrowDown')
  const okc = await gotoCol(page, '単価')
  log('found 単価 col in view6:', okc, 'cursor', await T.cursor(page))
  await page.keyboard.press('Enter')
  await page.keyboard.press('Control+a')
  await page.keyboard.type('1,200')
  await page.keyboard.press('Enter')
  log('purchasing price edit: toast', await T.toast(page), 'mode', await T.mode(page))
  await page.keyboard.press('Control+z')
  // PM が型式編集 / Shift+I / a
  await fresh(page, 'pm')
  await sel(page, 'R020')
  await gotoCol(page, '型式')
  await page.keyboard.press('Enter')
  log('pm Enter on model (view1): mode', await T.mode(page), 'toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
  await page.keyboard.press('Shift+I')
  log('pm Shift+I: panel', await T.panel(page), 'toast', await T.toast(page))
  await page.keyboard.press('Escape')
  await page.keyboard.press('a')
  log('pm a:', await T.toast(page))
  await page.keyboard.press('y')
  log('pm y on non-decision row:', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
  await page.keyboard.press('7')
  await page.keyboard.press('ArrowDown')
  log('pm view 7 first row:', await T.cursor(page), 'rows', await T.rows(page))
  await page.keyboard.press('y')
  log('pm y on 7 row: panel', await T.panel(page), 'toast', await T.toast(page))
  await shot(page, 's04_pm_y')
  await page.keyboard.press('Enter')
  log('pm y Enter empty reason: panel', await T.panel(page), 'toast', await T.toast(page), 'cursor', await T.cursor(page))
  await page.keyboard.press('Escape')
} catch (e) { log('EXC', String(e)) }
log('console/page errors:', errors)
save(errors)
await browser.close()
