// S06: 行を開いて指摘を見て迷う新人（約10人）。ステータスバーのヒントだけで操作できるか
import { launch, fresh, T, makeLog, shot, sel, gotoCol } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('s06_detail')
try {
  await fresh(page)
  await page.keyboard.press('4')
  await page.keyboard.press('ArrowDown')
  log('4 first row:', await T.cursor(page), 'status:', await T.status(page))
  await page.keyboard.press('n')
  log('after n:', await T.cursor(page), 'status:', await T.status(page))
  await page.keyboard.press('Space')
  await shot(page, 's06_detail_open')
  const issues = await page.getByTestId('issues').allTextContents()
  log('issues:', issues.join(' || ').slice(0, 300))
  log('status with detail open:', await T.status(page))
  // ↓ で指摘を選ぶ → ステータスバーに変化？
  await page.keyboard.press('ArrowDown')
  log('after ArrowDown: status', await T.status(page), 'focused li', await page.locator('.issues li.focus').count())
  await page.keyboard.press('Enter')
  log('Enter on issue: panel', await T.panel(page), 'options', (await page.getByTestId('quickfix').allTextContents().catch(() => [])).join(' ').slice(0, 300))
  await shot(page, 's06_issue_actions')
  // 間違ったキー 'z' / '9' / 'a' をパネルで押す
  await page.keyboard.press('z'); log('z in action panel: panel', await T.panel(page), 'toast', await T.toast(page))
  await page.keyboard.press('9'); log('9 in action panel: panel', await T.panel(page), 'view', await T.view(page))
  await page.keyboard.press('a'); log('a in action panel: panel', await T.panel(page))
  // 2 直さず回答 → 空で Enter
  await page.keyboard.press('2')
  log('2 -> panel', await T.panel(page), 'title', (await page.locator('.dialog h3').textContent().catch(() => '')))
  await page.keyboard.press('Enter')
  log('Enter empty reason: toast', await T.toast(page), 'panel', await T.panel(page))
  await page.getByTestId('prompt-text').fill('仕様書通りです')
  await page.keyboard.press('Enter')
  log('answered: issues', (await page.getByTestId('issues').allTextContents()).join(' ').slice(0, 200), 'status', await T.status(page))
  // 指摘を直す流れ: n → Enter(編集) → 直す → Ctrl+Enter
  await page.keyboard.press('Escape')
  await page.keyboard.press('n')
  log('n again:', await T.cursor(page), 'statusbar', (await T.status(page)).replace(/72 bindings/, ''))
  await page.keyboard.press('Control+.')
  log('Ctrl+. options:', (await page.getByTestId('quickfix').allTextContents().catch(() => [])).join(' ').slice(0, 400))
  await shot(page, 's06_quickfix')
  await page.keyboard.press('Escape')
  // 指摘のある行でそのまま Enter → 編集。空で Enter。
  await page.keyboard.press('Enter')
  log('Enter on issue cell: mode', await T.mode(page), 'editor', await page.getByTestId('cell-editor').inputValue().catch(() => '-'))
  await page.keyboard.press('Enter')
  log('Enter w/o change: status', (await T.status(page)).match(/未公開 \d+ 行/)?.[0])
  // x を押す（指摘を確認済にしようとする設計）
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('x')
  log('design x on issue row: toast', await T.toast(page))
  // Shift+R 返信 空 Enter
  await page.keyboard.press('Shift+R')
  log('Shift+R panel', await T.panel(page))
  await page.keyboard.press('Enter')
  log('reply empty Enter: panel', await T.panel(page), 'toast', await T.toast(page))
  await page.keyboard.press('Escape')
  // Shift+X 差戻し（設計がやる）
  await page.keyboard.press('Shift+X')
  log('design Shift+X: panel', await T.panel(page), 'toast', await T.toast(page))
  await page.keyboard.press('Escape')
  // 詳細を開いたまま j で次の行へ → 開いたまま？ 
  await page.keyboard.press('1')
  await sel(page, 'R020')
  await page.keyboard.press('Space')
  await page.keyboard.press('j')
  log('j with detail open: cursor', await T.cursor(page), 'details open', await page.getByTestId('detail').count())
  await page.keyboard.press('Space')
  await page.keyboard.press('j')
  await page.keyboard.press('Space')
  log('3 rows opened: details', await page.getByTestId('detail').count())
  await shot(page, 's06_multi_detail')
  await page.keyboard.press('Escape')
  log('Esc closes which? details', await page.getByTestId('detail').count(), 'cursor', await T.cursor(page))
  // ↓ で見積行まで下り、Enter
  await sel(page, 'R020')
  await page.keyboard.press('Space')
  for (let i = 0; i < 6; i++) await page.keyboard.press('ArrowDown')
  log('ArrowDown x6 in detail: cursor', await T.cursor(page), 'focus quote row', await page.locator('table.quotes tr.focus').count())
  await page.keyboard.press('Enter')
  log('Enter on focused quote row: mode', await T.mode(page), 'panel', await T.panel(page), 'toast', await T.toast(page))
  await page.keyboard.press('Escape')
  // 要決定の行を設計が開いて y
  await page.keyboard.press('Escape')
  await page.keyboard.press('7')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Space')
  log('design in view 7 detail:', (await page.getByTestId('detail').textContent()).slice(0, 200))
  await page.keyboard.press('Enter')
  log('design Enter on 7 row: mode', await T.mode(page), 'toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
} catch (e) { log('EXC', String(e)) }
log('console/page errors:', errors)
save(errors)
await browser.close()
