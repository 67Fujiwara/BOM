// S07: 絞り込み入力・/ キー・戻れるか（約10人）
import { launch, fresh, T, makeLog, shot, sel } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('s07_filter')
try {
  await fresh(page)
  await page.getByTestId('filter').click()
  await page.keyboard.type('リレー')
  log('typed リレー: rows', await T.rows(page), 'view', await T.view(page))
  await page.keyboard.type('j4a1')
  log('typed j4a1 in filter: value', await page.getByTestId('filter').inputValue(), 'view', await T.view(page), 'toast', await T.toast(page))
  await page.getByTestId('filter').fill('リレー')
  await page.keyboard.press('Enter')
  log('Enter: active', await page.evaluate(() => document.activeElement?.className), 'cursor', await T.cursor(page), 'rows', await T.rows(page), 'filter', await page.getByTestId('filter').inputValue())
  await page.keyboard.press('j')
  log('j after Enter: cursor', await T.cursor(page))
  await page.keyboard.press('Escape')
  log('Esc in nav with filter: filter', await page.getByTestId('filter').inputValue(), 'rows', await T.rows(page), 'cursor', await T.cursor(page))
  await page.keyboard.press('/')
  log('/ : active', await page.evaluate(() => document.activeElement?.className))
  await page.keyboard.type('/abc')
  log('typed /abc: value', await page.getByTestId('filter').inputValue(), 'rows', await T.rows(page))
  await page.keyboard.press('Escape')
  log('Esc in filter: value', await page.getByTestId('filter').inputValue(), 'active', await page.evaluate(() => document.activeElement?.className), 'rows', await T.rows(page))
  await shot(page, 's07_filter_abc_esc')
  await page.keyboard.press('Escape')
  log('Esc again: value', await page.getByTestId('filter').inputValue(), 'rows', await T.rows(page))
  // 絞り込み中に Ctrl+K / ? / Ctrl+Enter / Ctrl+Z
  await page.keyboard.press('/')
  await page.keyboard.type('?')
  log('? in filter: panel', await T.panel(page), 'value', await page.getByTestId('filter').inputValue())
  await page.keyboard.press('Control+k')
  log('Ctrl+K in filter: panel', await T.panel(page))
  await page.keyboard.press('Escape')
  log('after Esc from palette: active', await page.evaluate(() => document.activeElement?.className), 'mode', await T.mode(page))
  await page.getByTestId('filter').fill('')
  await page.getByTestId('filter').click()
  await page.keyboard.press('Control+z')
  log('Ctrl+Z in filter: toast', await T.toast(page))
  await page.keyboard.press('Control+Enter')
  log('Ctrl+Enter in filter: toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Tab')
  log('Tab from filter: active', await page.evaluate(() => document.activeElement?.tagName + '.' + document.activeElement?.className))
  await page.keyboard.press('j')
  log('j after Tab: cursor', await T.cursor(page))
  // 大文字小文字・全角
  await page.getByTestId('filter').fill('fx5u')
  log('fx5u rows', await T.rows(page))
  await page.getByTestId('filter').fill('ＦＸ５Ｕ')
  log('ＦＸ５Ｕ rows', await T.rows(page))
  await page.getByTestId('filter').fill('R00')
  log('R00 rows', await T.rows(page))
  await page.getByTestId('filter').fill('見積済')
  log('見積済 rows', await T.rows(page))
  await page.getByTestId('filter').fill('')
  // f（セルの値で絞り込み）→ 解除方法が分かるか
  await page.keyboard.press('Escape')
  await sel(page, 'R005')
  await page.keyboard.press('f')
  log('f: chips', await page.locator('.toolbar .chip').allTextContents(), 'rows', await T.rows(page))
  await page.keyboard.press('1')
  log('after 1: chips', await page.locator('.toolbar .chip').allTextContents(), 'rows', await T.rows(page))
  await page.locator('.toolbar .chip').first().click().catch(() => {})
  log('click chip: chips', await page.locator('.toolbar .chip').allTextContents())
  await page.keyboard.press('Escape')
  log('Esc: chips', await page.locator('.toolbar .chip').allTextContents(), 'rows', await T.rows(page))
  // 絞り込みで0件のとき j / Enter / Shift+Enter
  await page.getByTestId('filter').fill('zzzz')
  await page.keyboard.press('Enter')
  log('0 rows: cursor', await T.cursor(page), 'rows', await T.rows(page))
  await page.keyboard.press('Enter')
  log('Enter with 0 rows: mode', await T.mode(page), 'toast', await T.toast(page))
  await page.keyboard.press('Shift+Enter')
  log('Shift+Enter with 0 rows: mode', await T.mode(page), 'cursor', await T.cursor(page), 'rows', await T.rows(page), 'filter', await page.getByTestId('filter').inputValue())
  await shot(page, 's07_insert_in_filtered')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+z')
  // 並び替え s の解除
  await sel(page, 'R005')
  await page.keyboard.press('s')
  log('s: chips', await page.locator('.toolbar .chip').allTextContents(), 'group rows', await page.getByTestId('group-row').count())
  await page.keyboard.press(']')
  log('] while sorted: toast', await T.toast(page))
  await page.keyboard.press('s')
  log('s again: chips', await page.locator('.toolbar .chip').allTextContents())
} catch (e) { log('EXC', String(e)) }
log('console/page errors:', errors)
save(errors)
await browser.close()
