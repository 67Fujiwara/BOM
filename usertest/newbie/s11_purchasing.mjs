// S11: 購買の新人（約10人）: Shift+I・発行・取り込み・x
import { launch, fresh, T, makeLog, shot, sel, gotoCol, clearToast } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('s11_purchasing')
try {
  await fresh(page, 'purchasing')
  log('purchasing default view:', await T.view(page), 'status', (await T.status(page)).slice(0, 100))
  await page.keyboard.press('9')
  await page.keyboard.press('ArrowDown')
  log('9 first row:', await T.cursor(page), 'hints', (await T.status(page)).slice(-150))
  // Shift+I → 種別一覧で迷う: 間違ったキー / 数字 / Enter / Esc
  await page.keyboard.press('Shift+I')
  log('issue panel:', await T.panel(page), (await page.getByTestId('issue-kinds').textContent()).slice(0, 300))
  await shot(page, 's11_issue_kinds')
  await page.keyboard.press('1'); log('press 1 in kinds: step still kinds?', await page.getByTestId('issue-kinds').count())
  await page.keyboard.press('Enter'); log('Enter in kinds:', await page.getByTestId('issue-kinds').count(), 'toast', await T.toast(page))
  await page.keyboard.press('ArrowDown'); log('ArrowDown in kinds:', await page.locator('[data-testid="issue-kinds"] .opt[aria-selected="true"]').count())
  await page.keyboard.press('z'); log('z in kinds:', await page.getByTestId('issue-kinds').count(), 'toast', await T.toast(page))
  await page.keyboard.press('x'); log('x in kinds:', await page.getByTestId('issue-kinds').count(), 'panel', await T.panel(page))
  await page.keyboard.press('K'); log('K (shift) in kinds -> text step?', await page.getByTestId('issue-text').count())
  await page.keyboard.press('k'); log('k in kinds -> text step?', await page.getByTestId('issue-text').count())
  // 本文空で Enter
  await page.keyboard.press('Enter')
  log('empty text Enter: panel', await T.panel(page), 'toast', await T.toast(page), 'status', (await T.status(page)).match(/未発行 \d+ 件/)?.[0])
  await page.keyboard.press('Space')
  log('after Space: detail issues', (await page.getByTestId('issues').textContent().catch(() => '-')).slice(0, 160))
  await shot(page, 's11_empty_issue')
  await page.keyboard.press('Space')
  // 下書きを消したい: Ctrl+Z / Shift+Delete
  await page.keyboard.press('Control+z')
  log('Ctrl+Z draft: toast', await T.toast(page), 'status', (await T.status(page)).match(/未発行 \d+ 件/)?.[0])
  // J で次の行に移って連続起票（本文を打ってから J）
  await page.keyboard.press('Shift+I'); await page.keyboard.press('m')
  await page.getByTestId('issue-text').fill('メーカを書いてください')
  await page.keyboard.press('Shift+J')
  log('Shift+J with text: panel', await T.panel(page), 'text', await page.getByTestId('issue-text').inputValue().catch(() => '-'), 'cursor', await T.cursor(page))
  await page.keyboard.press('Enter')
  log('Enter: toast', await T.toast(page))
  await page.keyboard.press('Shift+J')
  log('Shift+J in nav: cursor', await T.cursor(page))
  await page.keyboard.press('j')
  log('j in nav: cursor', await T.cursor(page))
  // 客先指定品・代替不可の行で起票できない種別
  await page.keyboard.press('1')
  const blocked = await page.evaluate(() => [...document.querySelectorAll('[data-row-id]')].map((tr) => [tr.dataset.rowId, tr.querySelector('td[data-col="procurement"]')?.textContent, tr.querySelector('td[data-col="altPolicy"]')?.textContent]).filter((x) => x[1] === '客先指定品' || x[2] === '不可').slice(0, 3))
  log('blocked candidates:', JSON.stringify(blocked))
  if (blocked.length) {
    await sel(page, blocked[0][0]); await page.keyboard.press('Shift+I'); await page.keyboard.press(blocked[0][1] === '客先指定品' ? 'k' : 'a')
    log('blocked kind: toast', await T.toast(page), 'panel', await T.panel(page), 'step text?', await page.getByTestId('issue-text').count())
    await page.keyboard.press('Escape')
  }
  // 廃番 + Tab で提案欄、提案欄で Enter
  await sel(page, 'R020'); await page.keyboard.press('Shift+I'); await page.keyboard.press('d')
  await page.getByTestId('issue-text').fill('廃番です')
  await page.keyboard.press('Tab')
  log('Tab -> proposal fields:', await page.getByTestId('proposal-model').count(), 'active', await page.evaluate(() => document.activeElement?.getAttribute('data-testid')))
  await page.keyboard.type('NEW-123')
  await page.keyboard.press('Tab')
  log('Tab in proposal: active', await page.evaluate(() => document.activeElement?.getAttribute('data-testid')), 'panel', await T.panel(page))
  await page.keyboard.type('オムロン')
  await page.keyboard.press('Enter')
  log('proposal Enter: toast', await T.toast(page))
  await shot(page, 's11_proposal')
  // Ctrl+Enter で発行
  await clearToast(page)
  await page.keyboard.press('Control+Enter')
  log('Ctrl+Enter publish issues: toast', await T.toast(page), 'panel', await T.panel(page), 'status', (await T.status(page)).match(/未発行 \d+ 件/)?.[0])
  // 設計に切替 → 4 → 指摘が見える → n → 開く → 提案適用
  await page.locator('.role button', { hasText: '設計' }).click(); await page.locator('.gridwrap').focus()
  await page.keyboard.press('4')
  log('design view4 count:', await page.getByTestId('view-4').textContent(), 'rows', await T.rows(page))
  await sel(page, 'R020'); await page.keyboard.press('Space')
  log('design sees issue R020:', (await page.getByTestId('issues').textContent()).slice(0, 200))
  await page.keyboard.press('Control+.')
  log('design Ctrl+. on R020:', (await page.getByTestId('quickfix').textContent()).slice(0, 300))
  await page.keyboard.press('1')
  await page.waitForTimeout(50)
  log('after apply proposal: toast', await T.toast(page), 'cursor', await T.cursor(page), 'R020 status', await page.locator('[data-row-id="R020"] .status-pill').textContent(), 'rows', await T.rows(page))
  await shot(page, 's11_after_proposal')
  // 購買: 概算見積を依頼 / 見積回答を取り込む（ゴミ貼り付け） / 正式見積を依頼
  await page.locator('.role button', { hasText: '購買' }).click(); await page.locator('.gridwrap').focus()
  await clearToast(page)
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('概算見積'); await page.keyboard.press('Enter')
  log('quotes.request prompt:', await page.locator('.dialog').textContent())
  await shot(page, 's11_quote_request')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(300)
  log('quotes.request Enter(empty): toast', await T.toast(page), 'panel', await T.panel(page))
  await page.getByTestId('prompt-text').fill('来週').catch(() => {})
  await page.keyboard.press('Enter')
  await page.waitForTimeout(300)
  log('quotes.request "来週": toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
  await clearToast(page)
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('見積回答'); await page.keyboard.press('Enter')
  log('import prompt:', (await page.locator('.dialog').textContent()).slice(0, 200))
  await page.keyboard.press('Enter')
  log('import panel:', await T.panel(page), (await page.locator('.dialog').textContent()).slice(0, 120))
  await page.getByTestId('import-text').fill('R004 100 5\nなんかの文字\nR005\t200\t3')
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(100)
  log('import junk: toast', await T.toast(page))
  await clearToast(page)
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('正式見積'); await page.keyboard.press('Enter')
  await page.waitForTimeout(300)
  log('formal request: toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
  // 購買の x（対応済の指摘を確認）: 手がかりはステータスバーのみ
  await page.keyboard.press('4'); await page.keyboard.press('ArrowDown')
  log('purchasing view4 first:', await T.cursor(page), 'hints', (await T.status(page)).slice(-160))
  await page.keyboard.press('x')
  log('purchasing x:', await T.toast(page))
  // 未発行の下書きを残したまま役割切替
  await clearToast(page)
  await page.keyboard.press('1'); await sel(page, 'R040'); await page.keyboard.press('Shift+I'); await page.keyboard.press('q'); await page.getByTestId('issue-text').fill('質問です'); await page.keyboard.press('Enter')
  await page.locator('.role button', { hasText: '設計' }).click(); await page.locator('.gridwrap').focus()
  log('switch role with draft issue: toast', await T.toast(page), 'design status', (await T.status(page)).slice(0, 80))
  await sel(page, 'R040'); await page.keyboard.press('Space')
  log('design sees draft of purchasing?', (await page.getByTestId('issues').textContent()).slice(0, 120))
  await page.keyboard.press('4')
  log('design view4 includes R040 draft?', await page.locator('[data-row-id="R040"]').count())
} catch (e) { log('EXC', String(e)) }
log('console/page errors:', errors)
save(errors)
await browser.close()
