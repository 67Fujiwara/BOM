// S12: PM の新人（約8人）: 7 要決定、y / Shift+Y / Enter、案件設定
import { launch, fresh, T, makeLog, shot, sel, gotoCol, clearToast, store } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('s12_pm')
try {
  await fresh(page, 'pm')
  log('pm default view:', await T.view(page), 'status', (await T.status(page)).slice(0, 100), 'chip', await page.locator('.toolbar .chip').allTextContents())
  // y on non-decision row (view 1)
  await sel(page, 'R020')
  await clearToast(page)
  await page.keyboard.press('y')
  log('pm y on R020 (非要決定): panel', await T.panel(page), 'title', await page.locator('.dialog h3').textContent().catch(() => '-'))
  await page.getByTestId('prompt-text').fill('承認します')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(50)
  log('pm y Enter: toast', await T.toast(page), 'decisions on R020', (await store(page)).projects[0].decisions.filter((d) => d.rowId === 'R020').length)
  await clearToast(page)
  await page.keyboard.press('Enter')
  log('pm Enter on R020 view1: mode', await T.mode(page), 'toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
  // 7 ビュー
  await page.keyboard.press('7'); await page.keyboard.press('ArrowDown')
  log('7 row:', await T.cursor(page), 'rows', await T.rows(page), 'hints', (await T.status(page)).slice(-140))
  await page.keyboard.press('Space')
  log('7 detail:', (await page.getByTestId('detail').textContent()).match(/要決定: [^P]+/)?.[0])
  await shot(page, 's12_view7')
  await page.keyboard.press('Enter')
  log('Enter decision panel:', await T.panel(page), (await page.getByTestId('quickfix').textContent()).slice(0, 300))
  await shot(page, 's12_decision_panel')
  await page.keyboard.press('z'); log('z in decision panel: panel', await T.panel(page))
  await page.keyboard.press('y'); log('y in decision panel: panel', await T.panel(page), 'title', await page.locator('.dialog h3').textContent().catch(() => '-'))
  await page.keyboard.press('Escape')
  await page.keyboard.press('Enter'); await page.keyboard.press('b')
  log('b: panel', await T.panel(page), 'title', await page.locator('.dialog h3').textContent().catch(() => '-'), 'toast', await T.toast(page))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(50)
  log('b Enter (no reason): toast', await T.toast(page), 'cursor', await T.cursor(page), 'rows in 7', await T.rows(page), 'R013 status', await page.locator('[data-row-id="R013"] .status-pill').textContent().catch(() => '(gone)'))
  await page.keyboard.press('Control+z')
  log('Ctrl+Z decision:', await T.toast(page), 'rows in 7', await T.rows(page))
  await clearToast(page)
  // Shift+Y with empty reason
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Shift+Y')
  log('Shift+Y: panel', await T.panel(page), 'title', await page.locator('.dialog h3').textContent().catch(() => '-'))
  await page.keyboard.press('Enter')
  log('Shift+Y Enter empty: toast', await T.toast(page), 'panel', await T.panel(page))
  await page.keyboard.press('Escape')
  // 案件設定: PM が y で確定（未確定チップ）。納期に「来月」
  await clearToast(page)
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('案件設定'); await page.keyboard.press('Enter')
  log('settings:', await T.panel(page), (await page.getByTestId('settings').textContent()).slice(0, 120))
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
  log('edit dueDate: input', await page.getByTestId('settings-input').count())
  await page.getByTestId('settings-input').fill('来月')
  await page.keyboard.press('Enter')
  log('after Enter draft:', (await page.getByTestId('settings').textContent()).match(/案件納期[^社]+/)?.[0])
  await page.keyboard.press('Control+Enter')
  await page.waitForTimeout(100)
  log('Ctrl+Enter: panel', await T.panel(page), 'impact', await page.getByTestId('impact').textContent().catch(() => '-'), 'toast', await T.toast(page))
  await shot(page, 's12_settings_raigetsu')
  await page.keyboard.press('Enter')
  log('impact Enter: panel', await T.panel(page), 'title', await page.locator('.dialog h3').textContent().catch(() => '-'))
  await page.getByTestId('prompt-text').fill('テスト').catch(() => {})
  await page.keyboard.press('Enter')
  await page.waitForTimeout(100)
  log('after reason: panel', await T.panel(page), 'header due', (await T.header(page)).match(/納期[^概]+/)?.[0], 'toast', await T.toast(page))
  await shot(page, 's12_header_after_raigetsu')
  await page.keyboard.press('Control+z')
  log('Ctrl+Z settings:', await T.toast(page), 'header due', (await T.header(page)).match(/納期[^概]+/)?.[0])
  // 設計が案件設定の PM 項目を編集しようとする
  await page.locator('.role button', { hasText: '設計' }).click(); await page.locator('.gridwrap').focus()
  await clearToast(page)
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('案件設定'); await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  log('design edit name: toast', await T.toast(page))
  await page.keyboard.press('y')
  log('design y in settings: toast', await T.toast(page))
  await page.keyboard.press('Escape')
  // PM が 7 で Space→↓→Enter（指摘パネルと決定パネルの衝突）
  await page.locator('.role button', { hasText: 'PM' }).click(); await page.locator('.gridwrap').focus()
  await page.keyboard.press('7'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Space'); await page.keyboard.press('ArrowDown')
  log('PM 7 detail ArrowDown: status', (await T.status(page)).slice(0, 60), 'focus li', await page.locator('.issues li.focus').count())
  await page.keyboard.press('Enter')
  log('PM Enter after ArrowDown in 7:', await T.panel(page), (await page.getByTestId('quickfix').textContent().catch(() => '-')).slice(0, 120))
  await page.keyboard.press('Escape')
  // PM が 案件設定を確定（settings.confirm）
  await clearToast(page)
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('案件設定を確定'); await page.keyboard.press('Enter')
  await page.waitForTimeout(50)
  log('settings.confirm: toast', await T.toast(page), 'panel', await T.panel(page), 'header', (await T.header(page)).match(/重み：[^設]+/)?.[0], 'view7 count', await page.getByTestId('view-7').textContent())
} catch (e) { log('EXC', String(e)) }
log('console/page errors:', errors)
save(errors)
await browser.close()
