// S14: 追加確認（公開ゲートの順序・公開後の Ctrl+Z・Shift+A の範囲外・パレットの Tab・Ctrl+. 候補なし）
import { launch, fresh, T, makeLog, shot, sel, gotoCol, clearToast, store } from './lib.mjs'
const { browser, page, errors } = await launch()
const { log, save } = makeLog('s14_extra')
try {
  await fresh(page)
  // 1. エラー付き下書き行 + Ctrl+Enter → 先に Rev を聞く？
  await sel(page, 'R010'); await page.keyboard.press('Shift+Enter'); await page.keyboard.type('新しい部品'); await page.keyboard.press('Enter')
  log('new draft row:', await T.cursor(page), 'lamps', await page.getByTestId('lamps').textContent(), 'status', (await T.status(page)).match(/未公開 \d+ 行/)?.[0])
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+Enter')
  log('Ctrl+Enter with error draft: panel', await T.panel(page), 'title', await page.locator('.dialog h3').textContent().catch(() => '-'), 'toast', await T.toast(page))
  await shot(page, 's14_publish_prompt_then_error')
  if (await T.panel(page)) { await page.keyboard.press('1'); await page.waitForTimeout(50) }
  log('after choosing Rev: toast', await T.toast(page))
  await shot(page, 's14_publish_blocked')
  await page.keyboard.press('Control+z'); await page.keyboard.press('Control+z')
  // 2. 公開後の Ctrl+Z
  await clearToast(page)
  await sel(page, 'R030'); await gotoCol(page, '型式'); await page.keyboard.press('Enter'); await page.keyboard.press('Control+a'); await page.keyboard.type('M22N-XYZ'); await page.keyboard.press('Enter')
  await page.keyboard.press('Control+Enter')
  log('publish prompt:', await page.locator('.dialog h3').textContent().catch(() => '-'), 'options', await page.getByTestId('prompt-options').textContent().catch(() => '-'))
  if ((await T.panel(page)) === 'panel-prompt' && (await page.getByTestId('prompt-text').count())) { await page.keyboard.press('1') } else await page.keyboard.press('1')
  await page.waitForTimeout(100)
  log('after publish: toast', await T.toast(page), 'panel', await T.panel(page), 'rev-info', await page.getByTestId('rev-info').textContent().catch(() => '-'))
  if (await T.panel(page)) { await page.keyboard.press('1'); await page.waitForTimeout(100); log('2nd prompt -> toast', await T.toast(page), 'rev', await page.getByTestId('rev-info').textContent().catch(() => '-')) }
  await clearToast(page)
  await page.keyboard.press('Control+z')
  log('Ctrl+Z after publish: toast', await T.toast(page), 'R030 model', await page.locator('[data-row-id="R030"] td.model').textContent(), 'rev-info', await page.getByTestId('rev-info').textContent().catch(() => '-'), 'status', (await T.status(page)).match(/未公開 \d+ 行/)?.[0])
  await shot(page, 's14_undo_after_publish')
  // 3. Shift+A で範囲外の数字 / Enter
  await clearToast(page)
  await sel(page, 'R020'); await page.keyboard.press('Shift+A')
  const n = await page.getByTestId('adopt').locator('.opt').count()
  await page.keyboard.press('9'); log(`Shift+A press 9 (n=${n}): panel`, await T.panel(page), 'toast', await T.toast(page))
  await page.keyboard.press('Enter'); log('Shift+A Enter: panel', await T.panel(page), 'toast', await T.toast(page), 'R020', await page.locator('[data-row-id="R020"] .status-pill').textContent())
  await page.keyboard.press('Control+z')
  // 4. パレットで Tab
  await page.keyboard.press('Control+k'); await page.keyboard.press('Tab')
  log('Tab in palette: active', await page.evaluate(() => document.activeElement?.tagName + '.' + document.activeElement?.className), 'panel', await T.panel(page))
  await page.keyboard.type('公開')
  log('typed after Tab: input', await page.getByTestId('palette-input').inputValue())
  await page.keyboard.press('Escape')
  // 5. Ctrl+. 候補なし
  await clearToast(page)
  await sel(page, 'R002'); await page.keyboard.press('Control+.')
  log('Ctrl+. on clean row:', await T.panel(page), (await page.getByTestId('quickfix').textContent().catch(() => '-')).slice(0, 80))
  await page.keyboard.press('Enter'); log('Enter in empty quickfix: panel', await T.panel(page))
  await page.keyboard.press('Escape')
  // 6. 予算「100万」の案件
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('新しいBOM'); await page.keyboard.press('Enter')
  await page.getByTestId('wizard-id').fill('B-1'); await page.keyboard.press('Enter'); await page.getByTestId('wizard-name').fill('予算案件'); await page.keyboard.press('Enter'); await page.keyboard.press('Enter'); await page.keyboard.press('Enter')
  await page.getByTestId('wizard-budget').fill('100万'); await page.keyboard.press('Enter'); await page.keyboard.press('Enter'); await page.keyboard.press('Enter')
  await page.getByTestId('wizard-paste').fill('制御\tリレー\tMY4N\tオムロン\t4\t個\tKA1'); await page.keyboard.press('Control+Enter'); await page.keyboard.press('Enter'); await page.waitForTimeout(50)
  log('budget 100万 header:', (await T.header(page)).match(/概算[^重]+/)?.[0])
  await shot(page, 's14_budget_nan')
  // 7. 案件設定を設計が開いて Enter 連打
  await page.keyboard.press('Control+k'); await page.getByTestId('palette-input').fill('案件設定'); await page.keyboard.press('Enter')
  for (let i = 0; i < 3; i++) await page.keyboard.press('Enter')
  log('design Enter x3 in settings: toast', await T.toast(page), 'editing input', await page.getByTestId('settings-input').count())
  for (let i = 0; i < 11; i++) await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  log('design edits 購買 field: toast', await T.toast(page), 'input', await page.getByTestId('settings-input').count())
  await page.keyboard.press('Escape')
  log('Esc while editing settings field: panel', await T.panel(page))
  await page.keyboard.press('Escape')
  // 8. 編集中に役割ボタンをクリック
  await page.locator('.side .view', { hasText: '第3ライン' }).click()
  await sel(page, 'R031'); await gotoCol(page, '部品名'); await page.keyboard.press('Enter'); await page.keyboard.type('ABC')
  await page.locator('.role button', { hasText: '購買' }).click()
  log('role click during edit: mode', await T.mode(page), 'R031 name', await page.locator('[data-row-id="R031"] td.name').textContent(), 'editor', await page.getByTestId('cell-editor').count())
  await page.keyboard.press('Enter')
  log('Enter after role click during edit: mode', await T.mode(page), 'toast', await T.toast(page), 'R031 name', await page.locator('[data-row-id="R031"] td.name').textContent())
  await shot(page, 's14_role_click_during_edit')
  // 9. ビューをクリックしながら編集中
  await page.locator('.role button', { hasText: '設計' }).click(); await page.locator('.gridwrap').focus()
  await sel(page, 'R032'); await gotoCol(page, '部品名'); await page.keyboard.press('Enter'); await page.keyboard.type('DEF')
  await page.getByTestId('view-4').click()
  log('view click during edit: mode', await T.mode(page), 'view', await T.view(page), 'cursor', await T.cursor(page), 'editor', await page.getByTestId('cell-editor').count())
  await page.keyboard.press('Enter')
  log('Enter: mode', await T.mode(page), 'R032 name', await page.locator('[data-row-id="R032"] td.name').textContent().catch(() => '(not in view)'))
  await page.keyboard.press('1')
  log('R032 name in view1:', await page.locator('[data-row-id="R032"] td.name').textContent())
} catch (e) { log('EXC', String(e)) }
log('console/page errors:', errors)
save(errors)
await browser.close()
