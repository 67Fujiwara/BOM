// 変更区分の列を「変更」「区分」「種別」などの見出しで認識する規則の取りこぼしと誤り: 普通の列（有無・○×・要不要・A/C/D 記号）を削除の印と読んで行を消さないか
const SRC = process.env.SRC ?? '/home/user/BOM/src'
const { parseBomPaste } = await import(SRC + '/io/paste.ts')
const T = (rows: string[][]) => rows.map((r) => r.join('\t')).join('\n')
const cases: Array<[string, string, string[]]> = [
  ['変更 ○/×', '変更', ['○', '×', '○', '×']],
  ['変更 有/無', '変更', ['有', '無', '有', '無']],
  ['変更 要/不要', '変更', ['要', '不要', '要', '不要']],
  ['変更 あり/なし', '変更', ['あり', 'なし', 'あり', 'なし']],
  ['変更 A/C/D', '変更', ['A', 'C', 'D', 'C']],
  ['変更 追加/削除/変更なし', '変更', ['追加', '削除', '変更なし', '追加']],
  ['区分 追加/変更/削除/不要', '区分', ['追加', '変更', '削除', '不要']],
  ['区分 D (欠品)', '区分', ['追加', '変更', 'D', 'd']],
  ['種別 追加/削除', '種別', ['追加', '削除', '追加', '削除']],
  ['種別 部品/不要', '種別', ['部品', '不要', '部品', '部品']],
  ['区分 新規/廃止品 (購入区分)', '区分', ['新規', '廃止品', '新規', '継続']],
  ['処置 要/不要', '処置', ['追加', '不要', '追加', '変更']],
  ['変更区分 ○/×', '変更区分', ['○', '×', '○', '×']],
  ['変更区分 X/-/追加', '変更区分', ['追加', 'X', '-', '追加']],
  ['変更区分 除外/抹消(部品の除外区分)', '変更区分', ['追加', '除外', '抹消', '追加']],
]
for (const [name, h, vals] of cases) {
  const rows = [[h, '部品名', '型式', '数量'], ...vals.map((v, i) => [v, `P${i}`, `M-${i}`, '1'])]
  const r = parseBomPaste(T(rows))
  console.log(`${name.padEnd(34)} rows=${r.rows.length}/${vals.length} kept=${r.rows.map((x: any) => x.name).join(',')}  ${r.warnings.filter((w: string) => /削除/.test(w)).map((w: string) => w.slice(0, 50)).join('／')}`)
}
